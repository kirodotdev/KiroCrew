"use strict";

// Serialize an Electron submenu for the Windows custom-titlebar menu surface and
// dispatch the picked command back through the real MenuItem, so roles, checked
// state and accelerator labels keep behaving exactly as the native menu did.
//
// Two Electron internals this must mirror (lib/browser/api/menu-item.ts and
// menu.ts) — getting either wrong silently degrades only the `{ role: ... }`
// items, i.e. the whole Edit menu:
//
//   1. `item.accelerator` is null for role items. Electron 33 does not expose
//      the generated role defaults on Windows, so reading only the property strips
//      the Ctrl+C/Ctrl+V hints off Edit, Window > Close, View > Full Screen…
//   2. Electron's own menu delegate invokes
//      `item.click(KeyboardEvent, focusedWindow, focusedWebContents)`, and role
//      dispatch reads those last two arguments — `windowMethod(focusedWindow)`
//      or `webContentsMethod(focusedWebContents)`. The third argument MUST be a
//      real WebContents; passing anything else (an IpcMainEvent, say) makes
//      undo/redo/cut/copy/paste/delete/selectAll throw instead of run.

// Menu items are activated by pointer here, never by an accelerator, so no
// modifier is held. Shape matches Electron's menu KeyboardEvent.
const MENU_KEYBOARD_EVENT = Object.freeze({
  shiftKey: false,
  ctrlKey: false,
  altKey: false,
  metaKey: false,
  triggeredByAccelerator: false,
});

// Electron 33 does not expose getDefaultRoleAccelerator() on the MenuItems
// generated by `editMenu` / `windowMenu` on Windows. Keep the standard Windows
// labels visible in the renderer menu instead of silently dropping every Edit
// shortcut. Explicit accelerators still win for application-defined commands.
const WINDOWS_ROLE_ACCELERATORS = Object.freeze({
  undo: "Ctrl+Z",
  redo: "Ctrl+Y",
  cut: "Ctrl+X",
  copy: "Ctrl+C",
  paste: "Ctrl+V",
  pasteandmatchstyle: "Ctrl+Shift+V",
  delete: "Delete",
  selectall: "Ctrl+A",
  close: "Ctrl+W",
  togglefullscreen: "F11",
});

function acceleratorFor(item) {
  if (item.accelerator) return item.accelerator;
  const roleAccelerator = WINDOWS_ROLE_ACCELERATORS[String(item.role || "").toLowerCase()];
  if (roleAccelerator) return roleAccelerator;
  if (typeof item.getDefaultRoleAccelerator !== "function") return "";
  try {
    return item.getDefaultRoleAccelerator() || "";
  } catch {
    return ""; // item mid-teardown; the label alone is still useful
  }
}

function serializeMenuItems(submenu) {
  if (!submenu || !Array.isArray(submenu.items)) return [];
  return submenu.items.flatMap((item, index) => {
    if (!item.visible) return [];
    if (item.type === "separator") return [{ type: "separator", index }];
    return [{
      type: item.type || "normal",
      index,
      label: item.label,
      accelerator: acceleratorFor(item),
      enabled: item.enabled,
      checked: item.checked,
    }];
  });
}

function executeMenuItem(topLevelItem, index, win, targetWebContents) {
  const item = topLevelItem && topLevelItem.submenu && topLevelItem.submenu.items[index];
  if (!item || !item.visible || !item.enabled || typeof item.click !== "function") return false;
  item.click(MENU_KEYBOARD_EVENT, win, targetWebContents);
  return true;
}

module.exports = {
  serializeMenuItems,
  executeMenuItem,
  MENU_KEYBOARD_EVENT,
  WINDOWS_ROLE_ACCELERATORS,
};
