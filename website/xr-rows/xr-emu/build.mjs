// Builds iwer-init.js = IWER's own UMD build (node_modules/iwer/build/iwer.js,
// self-contained, no imports) + emu-glue.js, as one classic script.
// Run: node build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(here, 'node_modules/iwer/package.json'), 'utf8'));
const umd = readFileSync(join(here, 'node_modules/iwer/build/iwer.js'), 'utf8');
const glue = readFileSync(join(here, 'emu-glue.js'), 'utf8');
const out =
  `/* xr-emu init script. Generated by build.mjs; do not edit.\n` +
  ` * IWER ${pkg.version} (MIT, Meta Platforms) UMD build + emu-glue.js. */\n` +
  umd + '\n;\n' + glue;
writeFileSync(join(here, 'iwer-init.js'), out);
console.log(`iwer-init.js written (${out.length} bytes, iwer ${pkg.version})`);
