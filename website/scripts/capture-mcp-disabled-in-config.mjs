/**
 * Screenshot harness for #13075: Connections -> MCP Servers keeps a server that
 * is marked disabled in the shared Kiro MCP config, through Discover & Sync and
 * through a probe, as a greyed row with a "Disabled in config" badge and a
 * "N disabled" count in the section header -- the Kiro IDE's own treatment of
 * the same entry -- instead of silently dropping it.
 *
 * Runs the REAL built SPA (website/dist) behind the shared in-process static
 * server, every /api/** call answered from fixtures via Playwright route
 * interception -- gateway-free, no kiro-cli, no pod token.
 *
 * The fixture rows are the backend's own: `ROWS_AFTER` is what GET /api/mcp
 * emits, on this branch, for the issue's observed config (7 servers in the
 * Kiro-global mcp.json, 3 of them `disabled: true`, agent config holding the 4
 * enabled ones -- the post-sync state), generated by running `list_servers()` +
 * the handler's `_stamp_config_state` over a seeded home. The enabled rows carry
 * a probe result on top (`status: 'ok'` + tools + probedAt), which is how a
 * probed panel reads. `ROWS_BEFORE` is the same list minus the three disabled
 * rows: the fix only ADDS rows to this endpoint, so that is exactly what `main`
 * answers after a sync, and enabled rows render identically on both (pinned by
 * McpTab.test.tsx "leaves enabled rows exactly as before").
 *
 * Scenes (dark, plus the after-scene in light):
 *   1-before-after-sync   main's shape: 4 rows, "MCP Servers (4)", nothing says
 *                         three configured servers were left out.
 *   2-after-after-sync    this branch: 7 rows, "MCP Servers (7)  3 disabled",
 *                         figma / cupertino greyed with the muted badge, slack
 *                         (a non-boolean value) ungreyed with a "Config error"
 *                         chip and Status in the error tone; every disabled
 *                         row's scope badges inert, Status "Disabled", one line
 *                         naming the file to edit (the value to repair, for
 *                         slack), Uninstall live with its hover text.
 *   3-after-probe         the probe button pressed: POST /api/mcp/probe answers
 *                         the branch's shape (disabled rows included, unprobed)
 *                         and the three rows are still there.
 *   4-after-copy-failed   the path chip clicked with the clipboard refusing:
 *                         the failure renders as an ErrorNotice stacked under
 *                         the sentence (Ask the agent + Dismiss), never as Copied.
 *
 * Every scene asserts its rendered state before a frame is written, so a run
 * cannot emit a frame that contradicts the diff.
 *
 * Usage: node scripts/capture-mcp-disabled-in-config.mjs [outDir]
 */
import { chromium } from 'playwright'
import { mkdirSync } from 'node:fs'
import { serveDist } from './lib/serve-dist.mjs'
import { json, logPageProblems, stubDashboardApi } from './lib/stub-dashboard-api.mjs'

const OUT = process.argv[2] || '../temp-screenshots/mcp-disabled-in-config'
mkdirSync(OUT, { recursive: true })

const PRESENCE = { kirocrew: true, kiroGlobal: true, ccGlobal: false }
const PROBED_AT = Math.floor(Date.now() / 1000) - 90
// The backend collapses the home prefix to `~` before it names the file.
const SHARED_FILE = '~/.kiro/settings/mcp.json'
const WHERE_LINE = `Disabled in ${SHARED_FILE}. Editing this file lifts its disable; another config may still keep the server off. A switch is planned.`
// A `disabled` that is not a boolean is read fail-closed by the backend and the
// row says so: the fix is to repair the value, not to flip a switch.
const INVALID_WHERE_LINE = `Disabled: invalid "disabled" value in ${SHARED_FILE}. Set it to true or false there.`
const UNINSTALL_HELP = 'Removes this server from every MCP config, including the shared one it is disabled in.'

/** One enabled row as the backend emits it after a probe. */
const live = (name, transport, tools) => ({
  name,
  ...transport,
  status: 'ok',
  tools,
  error: '',
  source: 'agent',
  presence: PRESENCE,
  probeMode: 'handshake',
  probedAt: PROBED_AT,
  kirocrewManaged: false,
  enabled: true,
  disabledIn: null,
  disabledInFile: null,
  disabledReason: null,
})

/** One disabled row, verbatim from the backend (never probed, never started).
 *  `reason` is `'invalid'` for a row the backend muted over a non-boolean value. */
const off = (name, transport, reason = null) => ({
  name,
  ...transport,
  status: 'disabled',
  tools: [],
  error: '',
  source: 'mcp.json',
  presence: PRESENCE,
  probeMode: 'handshake',
  probedAt: 0.0,
  disabled: true,
  kirocrewManaged: false,
  enabled: false,
  disabledIn: 'shared',
  disabledInFile: SHARED_FILE,
  disabledReason: reason,
})

const ROWS_AFTER = [
  live('xcode-tools', { command: 'npx', args: ['-y', 'xcode-mcp-server'] }, ['build', 'run_tests', 'list_schemes']),
  live('github', { command: '', args: [], url: 'https://api.githubcopilot.com/mcp/' }, ['search_code', 'create_issue', 'get_pull_request']),
  live('atlassian', { command: '', args: [], url: 'https://mcp.atlassian.com/v1/mcp' }, ['search_jira', 'get_page']),
  live('datadog', { command: 'npx', args: ['-y', '@datadog/mcp-server'] }, ['query_metrics', 'list_monitors']),
  off('figma', { command: 'npx', args: ['-y', 'figma-developer-mcp', '--stdio'] }),
  off('cupertino', { command: 'uvx', args: ['cupertino-mcp'] }),
  // `"disabled": "false"` in the shared file: muted fail-closed, named as such.
  off('slack', { command: '', args: [], url: 'https://mcp.slack.com/mcp' }, 'invalid'),
]
const ROWS_BEFORE = ROWS_AFTER.filter(r => r.enabled)
const DISABLED_NAMES = ROWS_AFTER.filter(r => !r.enabled).map(r => r.name)
const WHERE_LINE_FOR = Object.fromEntries(
  ROWS_AFTER.filter(r => !r.enabled).map(r => [r.name, r.disabledReason === 'invalid' ? INVALID_WHERE_LINE : WHERE_LINE]),
)

async function capture(theme, scenes) {
  const { srv, base } = await serveDist()
  const browser = await chromium.launch()
  const context = await browser.newContext({
    viewport: { width: 1400, height: 900 },
    deviceScaleFactor: 1,
    colorScheme: theme,
  })
  const page = await context.newPage()
  page.setDefaultTimeout(15_000)
  logPageProblems(page)

  // Which list the stub serves. Flipped per scene, so one page load can show
  // the before-shape and the after-shape without a second server.
  let rows = ROWS_BEFORE
  await stubDashboardApi(page, {
    theme,
    slots: [],
    localStorageEntries: { 'mc-onboarded': '1', 'mc-theme-mode': theme },
    extra: async (path, route) => {
      if (path === '/api/config/kirocrew') return json(route, { connections_ui: true }), true
      if (path === '/api/theme/boot') return json(route, { mode: theme, theme: '' }), true
      // GET /api/mcp and POST /api/mcp/probe answer the SAME list on this
      // branch: the probe no longer leaves disabled rows out.
      if (path === '/api/mcp' || path === '/api/mcp/probe') return json(route, rows), true
      if (path === '/api/mcp/global-scopes') return json(route, { scopes: [] }), true
      if (path === '/api/connections/status') return json(route, { schema_version: 1, connections: [] }), true
      if (path === '/api/connections/mint') return json(route, { slug: '', state: 'idle' }), true
      if (path.startsWith('/api/chat/slots/')) {
        return json(route, { running: false, has_more: false, total: 0, queue: [], messages: [] }), true
      }
      return false
    },
  })

  const shot = async name => {
    await page.waitForTimeout(600)
    const file = `${OUT}/${name}-${theme}.png`
    await page.screenshot({ path: file })
    console.log('wrote', file)
  }

  const table = page.locator('#connections-mcp-panel table')
  const dataRows = () => table.locator('tbody tr')
  const badge = name => table.locator('tbody tr', { has: page.locator(`code:text-is("${name}")`) })

  const expectRows = async (want, disabledWant) => {
    const seen = await dataRows().count()
    if (seen !== want) throw new Error(`expected ${want} rows in the MCP table, saw ${seen}`)
    const greyed = await table.locator('tbody tr[data-disabled-in-config="true"]').count()
    if (greyed !== disabledWant) throw new Error(`expected ${disabledWant} greyed rows, saw ${greyed}`)
    const count = page.getByTestId('mcp-disabled-count')
    if (disabledWant === 0) {
      if (await count.count() !== 0) throw new Error('a "N disabled" count is shown with nothing disabled')
      if (await page.getByText('Disabled in config').count() !== 0) throw new Error('a badge is shown with nothing disabled')
      return
    }
    await count.waitFor({ state: 'visible' })
    const text = (await count.innerText()).trim()
    if (text !== `${disabledWant} disabled`) throw new Error(`header count reads ${JSON.stringify(text)}`)
    for (const name of DISABLED_NAMES) {
      const row = badge(name)
      const invalid = ROWS_AFTER.find(r => r.name === name)?.disabledReason === 'invalid'
      // A deliberate disable is an off switch: muted "Disabled in config" chip,
      // muted Status, non-actionable cells greyed. A non-boolean value is a
      // CONFIG ERROR to repair: "Config error" chip and Status in the error
      // tone, and nothing greyed -- grey would read as "deliberately off".
      const chip = row.getByTestId(invalid ? 'mcp-config-error-chip' : 'mcp-disabled-in-config-chip')
      await chip.waitFor({ state: 'visible' })
      const chipText = (await chip.innerText()).trim()
      if (chipText !== (invalid ? 'Config error' : 'Disabled in config')) throw new Error(`${name}: the chip reads ${JSON.stringify(chipText)}`)
      const status = row.getByText(invalid ? 'Invalid value' : 'Disabled', { exact: true })
      await status.waitFor({ state: 'visible' })
      const tone = invalid ? 'text-danger' : 'var(--muted)'
      for (const [what, el] of [['chip', chip], ['status', status]]) {
        const cls = (await el.getAttribute('class')) ?? ''
        if (!cls.includes(tone)) throw new Error(`${name}: the ${what} is not in the ${invalid ? 'error' : 'muted'} tone (${cls})`)
      }
      const dimmed = await row.locator('td').evaluateAll(cells => cells.map(c => c.style.opacity))
      if (invalid && dimmed.some(o => o !== '')) throw new Error(`${name}: an invalid-value row is greyed (${dimmed.join(',')})`)
      if (!invalid && (dimmed.slice(0, 5).some(o => o !== '0.6') || dimmed[5] !== '')) throw new Error(`${name}: dimming reads ${dimmed.join(',')}`)
      // The explanation is ON the row, in words, naming the file to edit --
      // and, for a value the backend read fail-closed, the value to repair.
      const where = row.getByTestId('mcp-disabled-in-config-where')
      await where.waitFor({ state: 'visible' })
      const whereText = (await where.innerText()).trim()
      if (whereText !== WHERE_LINE_FOR[name]) throw new Error(`${name}: the where-line reads ${JSON.stringify(whereText)}`)
      // Uninstall still purges the name from every config, so it stays live
      // and its hover text says so; the scope toggles are the inert controls.
      const uninstall = row.getByRole('button', { name: 'Uninstall' })
      if (!(await uninstall.isEnabled())) {
        throw new Error(`${name}: Uninstall is greyed out on a row it would still remove`)
      }
      if ((await uninstall.getAttribute('title')) !== UNINSTALL_HELP) {
        throw new Error(`${name}: Uninstall hover text reads ${JSON.stringify(await uninstall.getAttribute('title'))}`)
      }
      for (const scope of ['kirocrew', 'kiroGlobal']) {
        if (await row.locator(`button[data-scope="${scope}"]`).isEnabled()) {
          throw new Error(`${name}: the ${scope} scope badge is live on a row disabled in the shared config`)
        }
      }
    }
    // Enabled rows keep every control and carry none of the disabled copy.
    const github = badge('github')
    if (!(await github.getByRole('button', { name: 'Uninstall' }).isEnabled())) {
      throw new Error('an enabled row lost its Uninstall')
    }
    if (await github.getByRole('button', { name: 'Uninstall' }).getAttribute('title')) {
      throw new Error('an enabled row carries the disabled-row Uninstall hover text')
    }
    if (await github.getByText('Disabled in config').count() !== 0) throw new Error('an enabled row carries the badge')
    if (await github.getByTestId('mcp-disabled-in-config-where').count() !== 0) throw new Error('an enabled row carries the where-line')
  }

  await page.goto(base + '/capabilities?tab=mcp', { waitUntil: 'domcontentloaded' })
  await page.locator('#connections-mcp-tab').waitFor({ state: 'visible', timeout: 20_000 })
  await page.locator('#connections-mcp-tab').click()
  await table.waitFor({ state: 'visible' })
  await page.locator('h4', { hasText: /MCP Servers \(4\)/ }).waitFor({ state: 'visible' })

  // 1. main's shape after a sync: the three disabled servers are simply not
  //    there, and nothing on the page says so.
  if (scenes.includes('before')) {
    await expectRows(4, 0)
    await shot('1-before-after-sync')
  }

  // 2. This branch's shape after the same sync: present, greyed, badged, counted.
  rows = ROWS_AFTER
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.locator('#connections-mcp-tab').waitFor({ state: 'visible', timeout: 20_000 })
  await page.locator('#connections-mcp-tab').click()
  await table.waitFor({ state: 'visible' })
  await page.locator('h4', { hasText: /MCP Servers \(7\)/ }).waitFor({ state: 'visible' })
  await expectRows(7, 3)
  await shot('2-after-after-sync')

  // 3. A probe (the refresh the issue calls Discover & Sync) repaints the table
  //    from POST /api/mcp/probe -- the three rows survive it.
  if (scenes.includes('probe')) {
    let probed = false
    await page.route('**/api/mcp/probe', async route => { probed = true; await json(route, rows) })
    await page.getByRole('button', { name: 'Probe MCP servers' }).click()
    await page.waitForTimeout(800)
    if (!probed) throw new Error('the probe request never left the page')
    await page.locator('h4', { hasText: /MCP Servers \(7\)/ }).waitFor({ state: 'visible' })
    await expectRows(7, 3)
    await shot('3-after-probe')
  }

  // 4. A refused clipboard: the path chip's copy fails, and the failure renders
  //    through ErrorNotice STACKED under the sentence -- the chip's row keeps
  //    one control, the notice carries Ask the agent + Dismiss, so no row holds
  //    more than two actions. Both clipboard layers are made to refuse here.
  if (scenes.includes('copy-failed')) {
    await page.evaluate(() => {
      const denied = () => Promise.reject(Object.assign(new Error('denied'), { name: 'NotAllowedError' }))
      Object.defineProperty(navigator, 'clipboard', { value: { writeText: denied }, configurable: true })
      document.execCommand = () => false
    })
    const figma = badge('figma')
    const chip = figma.getByTestId('mcp-disabled-in-config-path')
    await chip.click()
    const notice = figma.getByTestId('mcp-disabled-in-config-path-copy-failed')
    await notice.waitFor({ state: 'visible' })
    if ((await notice.evaluate(el => el.tagName)) !== 'DIV') throw new Error('the copy-failed notice is not stacked (inline variant)')
    const actions = await notice.getByRole('button').count()
    if (actions > 2) throw new Error(`the copy-failed notice carries ${actions} actions in one row`)
    if (await chip.getAttribute('data-copied')) throw new Error('a refused copy flashed as Copied')
    // Stacked: the notice starts below the chip's line.
    const [chipBox, noticeBox] = [await chip.boundingBox(), await notice.boundingBox()]
    if (!chipBox || !noticeBox || noticeBox.y < chipBox.y + chipBox.height - 1) {
      throw new Error(`the notice sits beside the chip, not under it (${JSON.stringify({ chipBox, noticeBox })})`)
    }
    await shot('4-after-copy-failed')
  }

  await browser.close()
  srv.close()
}

async function main() {
  await capture('dark', ['before', 'probe', 'copy-failed'])
  await capture('light', [])
}

main().catch(err => { console.error(err); process.exit(1) })
