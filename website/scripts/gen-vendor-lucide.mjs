/**
 * Generate `public/vendor/lucide-react.mjs` from the INSTALLED lucide-react.
 * Usage: node scripts/gen-vendor-lucide.mjs [--check]
 *   --check writes nothing and exits 1 when the file on disk is stale.
 *
 * No shebang: the test below imports this module, and on Windows Vite's CJS
 * interop prepends its requires to line 1, which would push a shebang after
 * executable code and make the importing test file collect zero tests
 * (src/test/scriptsShebang.test.ts).
 *
 * WHY THE STUB IS GENERATED. An installed app's UI bundle imports the bare
 * specifier `lucide-react`, which `index.html`'s import map resolves to that
 * stub, which reads the icons back out of the host registry
 * `src/app-sdk/shared-modules.ts` populates. ESM resolves NAMED imports at LINK
 * time against the target module's static export list, so an icon the stub does
 * not name fails the importing app module outright -- "does not provide an
 * export named 'X'", before a line of its code runs, which is also why the
 * stub's Proxy default export cannot stand in for it. Naming the whole
 * namespace is what lets an app import any icon the package ships; a list
 * written by hand bounds every app to whichever icons someone happened to add.
 *
 * Over-listing is safe: a name absent from the host registry destructures to
 * `undefined` instead of throwing, so the stub survives lucide-react dropping
 * an icon until the next regeneration.
 *
 * `buildStubSource` is exported so the test that catches a stale stub compares
 * against this generator rather than a second copy of these rules.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as lucide from 'lucide-react'

export const STUB_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'public',
  'vendor',
  'lucide-react.mjs',
)

/**
 * Words that cannot be bound by the `export const { ... } = m` destructuring
 * pattern the stub uses. lucide-react ships none of them today; excluding them
 * keeps a future export from emitting a file that will not parse.
 */
const RESERVED = new Set([
  'arguments', 'await', 'break', 'case', 'catch', 'class', 'const', 'continue',
  'debugger', 'default', 'delete', 'do', 'else', 'enum', 'eval', 'export',
  'extends', 'false', 'finally', 'for', 'function', 'if', 'import', 'in',
  'instanceof', 'let', 'new', 'null', 'return', 'static', 'super', 'switch',
  'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while', 'with',
  'yield',
])

/** Every installed export that can legally be named in the stub, sorted. */
export function exportNames(namespace = lucide) {
  return Object.keys(namespace)
    .filter((name) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name))
    .filter((name) => !RESERVED.has(name))
    .sort()
}

/** The exact bytes the stub must contain for the given export names. */
export function buildStubSource(names = exportNames()) {
  // Wrapped at ~96 columns: one name per line would make the file 5,800 lines
  // and every lucide bump an unreadable diff.
  const lines = []
  let line = ''
  for (const name of names) {
    const piece = ` ${name},`
    if (line.length + piece.length > 96) {
      lines.push(line)
      line = ''
    }
    line += piece
  }
  if (line.trim()) lines.push(line)

  return `// GENERATED by scripts/gen-vendor-lucide.mjs -- do not edit by hand.
// Vendor stub: an app bundle's \`import ... from 'lucide-react'\` resolves here
// through index.html's import map, and this reads the icons out of the host
// registry that src/app-sdk/shared-modules.ts populates.
//
// Every export of the installed lucide-react is named below because ESM resolves
// named imports at LINK time: an icon missing from the list fails the importing
// app module outright, before the Proxy below can stand in for it. Regenerate
// with \`npm run gen:vendor-lucide\` after bumping lucide-react.
const m = window.__kirocrew_modules?.['lucide-react']
if (!m) throw new Error('[vendor/lucide-react] Host modules not initialized. Ensure shared-modules.ts is loaded.')

// Keeps \`import icons from 'lucide-react'\` and any property access working.
export default new Proxy(m, { get: (_, prop) => m[prop] })

export const {
${lines.join('\n')}
} = m
`
}

/** True when this module was run as a script rather than imported by a test. */
const isEntryPoint = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]

if (isEntryPoint) {
  const source = buildStubSource()
  const count = exportNames().length
  if (process.argv.includes('--check')) {
    const current = existsSync(STUB_PATH) ? readFileSync(STUB_PATH, 'utf8') : ''
    if (current !== source) {
      console.error(`[gen-vendor-lucide] STALE: ${STUB_PATH} does not match lucide-react's exports.`)
      console.error('[gen-vendor-lucide] Run: npm run gen:vendor-lucide')
      process.exit(1)
    }
    console.log(`[gen-vendor-lucide] up to date (${count} exports)`)
  } else {
    writeFileSync(STUB_PATH, source)
    console.log(`[gen-vendor-lucide] wrote ${STUB_PATH} (${count} exports)`)
  }
}
