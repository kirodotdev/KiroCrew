/**
 * Generate the TypeScript declarations for `@kirocrew/app-sdk` and
 * `@kirocrew/app-sdk/ui`, as one file an app project adds to its sources.
 * Usage: node scripts/gen-app-sdk-types.mjs <out-file>
 *
 * `npm run build` writes it to `dist/vendor/kirocrew-app-sdk.d.ts`, so every
 * gateway serves the declarations of the exact SDK it hosts.
 *
 * The SDK's sources import most of the dashboard, so emitting the whole program
 * would publish every host module. Only the two barrels are emitted, then each
 * host module their declarations name, transitively. Each becomes a
 * `declare module` block: a barrel under its public specifier, a host module
 * under a `kirocrew-host:` name that no import map resolves, so an app cannot
 * mistake it for a public entry point.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

// TypeScript reports every path with forward slashes, Windows included.
const toPosix = (p) => p.split(path.sep).join('/')
const WEBSITE = toPosix(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'))
const SRC = `${WEBSITE}/src`
const ENTRIES = new Map([
  [`${SRC}/app-sdk/index.ts`, '@kirocrew/app-sdk'],
  [`${SRC}/kirocrew-ui/index.ts`, '@kirocrew/app-sdk/ui'],
])

const moduleName = (file) =>
  ENTRIES.get(file) ?? `kirocrew-host:${path.posix.relative(SRC, file).replace(/\.tsx?$/, '')}`

/** Every module specifier a declaration file names: imports, re-exports, `import("…")` types. */
function specifiers(source) {
  const found = []
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
      found.push(node.moduleSpecifier)
    } else if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)) {
      found.push(node.argument.literal)
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return found
}

function fail(diagnostics) {
  const detail = ts.formatDiagnostics(diagnostics, {
    getCanonicalFileName: (f) => f,
    getCurrentDirectory: () => WEBSITE,
    getNewLine: () => '\n',
  })
  throw new Error(`[gen-app-sdk-types] declaration emit failed for a module the app SDK's types reach:\n${detail}`)
}

/** The declaration file's text. */
function buildAppSdkTypes() {
  const config = ts.getParsedCommandLineOfConfigFile(
    `${WEBSITE}/tsconfig.app.json`,
    { noEmit: false, declaration: true, emitDeclarationOnly: true, incremental: false },
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic: (d) => fail([d]) },
  )
  // The ambient `.d.ts` files under src/ (vite-env, the Electron bridge) stay roots,
  // so the host's own globals resolve exactly as they do in `npm run typecheck`.
  const ambient = config.fileNames.filter((f) => f.endsWith('.d.ts'))
  const program = ts.createProgram({ rootNames: [...ambient, ...ENTRIES.keys()], options: config.options })
  const queue = [...ENTRIES.keys()]
  const emitted = new Set()
  const blocks = []
  while (queue.length) {
    const file = queue.shift()
    if (emitted.has(file)) continue
    emitted.add(file)
    let text = ''
    const result = program.emit(program.getSourceFile(file), (_, data) => { text = data }, undefined, true)
    if (result.diagnostics.length) fail(result.diagnostics)
    const declaration = ts.createSourceFile(`${file}.d.ts`, text, ts.ScriptTarget.Latest, true)
    const edits = []
    for (const specifier of specifiers(declaration)) {
      const resolved = ts.resolveModuleName(specifier.text, file, config.options, ts.sys).resolvedModule
      if (!resolved || resolved.isExternalLibraryImport) continue
      if (!resolved.resolvedFileName.startsWith(`${SRC}/`)) {
        throw new Error(`${file}: '${specifier.text}' resolves outside src/`)
      }
      queue.push(resolved.resolvedFileName)
      edits.push([specifier.getStart(declaration), specifier.end, `'${moduleName(resolved.resolvedFileName)}'`])
    }
    // Inside a `declare module` block every statement is already ambient, and a
    // second `declare` is an error (TS1038).
    for (const statement of declaration.statements) {
      const declare = ts.canHaveModifiers(statement)
        && ts.getModifiers(statement)?.find((m) => m.kind === ts.SyntaxKind.DeclareKeyword)
      if (declare) edits.push([declare.getStart(declaration), declare.end + 1, ''])
    }
    for (const [start, end, replacement] of edits.sort((a, b) => b[0] - a[0])) {
      text = text.slice(0, start) + replacement + text.slice(end)
    }
    blocks.push(`declare module '${moduleName(file)}' {\n${text.trimEnd()}\n}\n`)
  }
  return `// GENERATED by website/scripts/gen-app-sdk-types.mjs from this host's own SDK.\n\n${blocks.join('\n')}`
}

const out = process.argv[2]
if (!out) {
  console.error('usage: node scripts/gen-app-sdk-types.mjs <out-file>')
  process.exit(2)
}
writeFileSync(out, buildAppSdkTypes())
console.log(`[gen-app-sdk-types] wrote ${out}`)
