"""Assign whole files to CI shards before pytest imports their test modules.

Leave discovery to pytest: testpaths, filename patterns, conftest ignores and
explicit targets retain their normal semantics. Only the owning shard collects
a file's items. Unlike pytest-split, other shards never import that file merely
to discard its tests. Directory/conftest imports and imports made by tests are
still shared costs; this is not a promise of a particular wall-clock speedup.

A file's owner is the SHA-256 of its root-relative POSIX path, unless
``--file-shard-pins`` names a pin file that lists it. A pin file gives the
files it lists a fixed owner so the shards' total test time comes out even; it
is generated by ``scripts/ci_file_shard_pins.py`` from measured CI timings. A
file the pin file does not list (new, renamed) keeps its hash owner, so every
file still has exactly one owner, decided from its path alone.

``--file-shard-targets`` names a file listing the test files a subset run
wants, one root-relative path per line. Discovery still starts at testpaths but
skips every path that is not a target or a directory above one. The subset is
never put on argv: pytest walks a file argument's directory once per argument,
so a list of about 1,200 files takes up to an hour to collect. Spell it
``--file-shard-targets=PATH``: pytest picks its rootdir before this plugin's
options exist, so a separate PATH token outside the checkout counts as a test
argument there and can move the rootdir off the checkout.

A targets list is a small part of the suite, and neither the hash nor the pins
(placed for the whole suite) spread it evenly: two heavy files sharing a shard
set the run's time while the other shards finish early. So the listed files
are placed by measured time instead, heaviest first onto the shard with the
least time so far, ties going to the shard holding fewer files and then to the
lower shard number, and equal weights ordered by path. The seconds come from a
weights file ``scripts/ci_file_shard_pins.py`` writes next to the pin files,
one per platform; ``--file-shard-weights=PATH`` names another. A target the
weights file does not list (new, renamed) gets the file's median weight, so
unmeasured targets spread across the shards too. Every shard and every xdist
worker computes the same placement, because it depends only on the targets
list, the weights file and the shard count. Pins never apply to a target.
That makes the list part of the contract: every shard of a run must be given
the same set of targets, in any order. A hash owner holds whatever the other
shards were given; a placement does not, so shards given different sets could
each leave a file to another. No shard can see another's list, so each one
prints the SHA-256 of its target set and how many files it holds in the
terminal summary, where differing shards show. ``--file-shard-targets-sha256``
names the digest the run expects: a shard whose list has another one stops
before collecting. The digest is over the sorted root-relative paths, one per
line, which is ``LC_ALL=C sort -u <list> | sha256sum``.
"""

from __future__ import annotations

import hashlib
import heapq
import math
import statistics
import sys
from collections.abc import Iterable, Mapping
from pathlib import Path

import pytest

_HERE = Path(__file__).resolve().parent
DEFAULT_WEIGHTS = {
    "linux": _HERE / "ci_file_shard_weights.txt",
    "windows": _HERE / "ci_file_shard_weights_windows.txt",
}


def default_weights_path(platform: str | None = None) -> Path:
    """Return the checked-in weights file for ``sys.platform`` (Linux's off Windows)."""
    name = sys.platform if platform is None else platform
    return DEFAULT_WEIGHTS["windows" if name == "win32" else "linux"]


def hash_shard(relative: str, count: int) -> int:
    """Return the one-based hash owner of a root-relative POSIX path."""
    digest = hashlib.sha256(relative.encode("utf-8", errors="surrogatepass")).digest()
    return int.from_bytes(digest[:8], "big") % count + 1


def file_shard(path: Path, root: Path, count: int, pins: Mapping[str, int] | None = None) -> int:
    """Return a stable, one-based owner, independent of checkout path and OS."""
    relative = path.relative_to(root).as_posix()
    if pins and relative in pins:
        return pins[relative]
    return hash_shard(relative, count)


def read_pins(path: Path, count: int) -> dict[str, int]:
    """Parse a pin file: a ``# shards: N`` header, then ``<shard> <path>`` lines.

    Refuse anything ambiguous rather than guess an owner: a shard count other
    than the run's own (pins made for eight shards mean nothing for four), an
    owner outside 1..N, or a path listed twice.
    """
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise pytest.UsageError(f"cannot read --file-shard-pins {path}: {exc}") from exc
    declared = None
    pins: dict[str, int] = {}
    for number, line in enumerate(lines, 1):
        text = line.strip()
        if not text:
            continue
        if text.startswith("#"):
            key, _, value = text[1:].partition(":")
            if key.strip() == "shards":
                if not value.strip().isdigit():
                    raise pytest.UsageError(f"{path}:{number}: expected '# shards: <N>'")
                declared = int(value)
            continue
        owner, _, relative = text.partition(" ")
        if not owner.isdigit() or not relative or not 1 <= int(owner) <= count:
            raise pytest.UsageError(f"{path}:{number}: expected '<1..{count}> <path>'")
        if relative in pins:
            raise pytest.UsageError(f"{path}:{number}: {relative} is pinned twice")
        pins[relative] = int(owner)
    if declared != count:
        raise pytest.UsageError(
            f"{path} pins files for '# shards: {declared}', but --file-shards is {count}"
        )
    return pins


def read_targets(path: Path, root: Path) -> tuple[Path, ...]:
    """Parse a targets file: one root-relative test file per line, blanks skipped.

    Returned in file order with repeats dropped, so every shard sees one list.
    """
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise pytest.UsageError(f"cannot read --file-shard-targets {path}: {exc}") from exc
    targets = tuple(dict.fromkeys(root / line.strip() for line in lines if line.strip()))
    for target in targets:
        if not target.is_file():
            raise pytest.UsageError(f"--file-shard-targets {path} lists {target}, not a file")
    return targets


def read_weights(path: Path) -> dict[str, int]:
    """Parse a weights file: ``<seconds> <path>`` lines, as whole milliseconds.

    Integers keep the placement exact: summing floats in a different order
    could break a tie differently on two shards. Refuse a weight that is not a
    finite, non-negative number, or a path listed twice.
    """
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise pytest.UsageError(f"cannot read --file-shard-weights {path}: {exc}") from exc
    weights: dict[str, int] = {}
    for number, line in enumerate(lines, 1):
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        value, _, relative = text.partition(" ")
        try:
            seconds = float(value)
        except ValueError:
            seconds = math.nan
        if not relative or not math.isfinite(seconds) or seconds < 0:
            raise pytest.UsageError(f"{path}:{number}: expected '<seconds> <path>'")
        if relative in weights:
            raise pytest.UsageError(f"{path}:{number}: {relative} is weighted twice")
        weights[relative] = round(seconds * 1000)
    return weights


def targets_digest(names: Iterable[str]) -> str:
    """Return the SHA-256 of a set of root-relative POSIX paths, whatever their order."""
    text = "".join(f"{name}\n" for name in sorted(set(names)))
    return hashlib.sha256(text.encode("utf-8", errors="surrogatepass")).hexdigest()


def balance(names: Iterable[str], weights: Mapping[str, int], count: int) -> dict[str, int]:
    """Place each name on a one-based shard, heaviest first onto the lightest.

    A name ``weights`` does not list weighs the median of ``weights``. The
    result depends on the SET of names alone, never on their order.
    """
    default = statistics.median_low(weights.values()) if weights else 0
    weight = {name: weights.get(name, default) for name in names}
    heap = [(0, 0, shard) for shard in range(1, count + 1)]
    owners = {}
    for name in sorted(weight, key=lambda name: (-weight[name], name)):
        load, files, shard = heapq.heappop(heap)
        owners[name] = shard
        heapq.heappush(heap, (load + weight[name], files + 1, shard))
    return owners


def pytest_addoption(parser: pytest.Parser) -> None:
    group = parser.getgroup("CI file sharding")
    group.addoption("--file-shards", type=int, default=None, help="Number of CI file shards")
    group.addoption("--file-shard", type=int, default=None, help="One-based CI file shard")
    group.addoption(
        "--file-shard-pins",
        default=None,
        help="Pin file giving listed files a fixed shard; other files keep their hash shard",
    )
    group.addoption(
        "--file-shard-targets",
        default=None,
        help="File listing the only test files to collect, one root-relative path per line",
    )
    group.addoption(
        "--file-shard-weights",
        default=None,
        help="Measured seconds per file, used to spread --file-shard-targets across the shards; "
        "default: the platform's checked-in weights file",
    )
    group.addoption(
        "--file-shard-targets-sha256",
        default=None,
        help="Refuse to run unless the --file-shard-targets set has this digest, so every "
        "shard of a run is proven to hold the same list",
    )


def pytest_configure(config: pytest.Config) -> None:
    count = config.getoption("file_shards")
    index = config.getoption("file_shard")
    pins_path = config.getoption("file_shard_pins")
    targets_path = config.getoption("file_shard_targets")
    weights_path = config.getoption("file_shard_weights")
    expected = config.getoption("file_shard_targets_sha256")
    if count is None and index is None:
        if any(value is not None for value in (pins_path, targets_path, weights_path, expected)):
            raise pytest.UsageError(
                "--file-shard-pins, --file-shard-targets, --file-shard-weights and "
                "--file-shard-targets-sha256 require --file-shards and --file-shard"
            )
        return
    if count is None or index is None or not 1 <= index <= count:
        raise pytest.UsageError("file sharding requires 1 <= --file-shard <= --file-shards")
    if config.getoption("splits", default=None):
        raise pytest.UsageError("file sharding cannot be combined with --splits")
    pins = read_pins(Path(pins_path), count) if pins_path is not None else {}
    targets = None
    weights = None
    if targets_path is not None:
        targets = read_targets(Path(targets_path), config.rootpath)
        weights = read_weights(
            Path(weights_path) if weights_path is not None else default_weights_path()
        )
    elif weights_path is not None or expected is not None:
        raise pytest.UsageError(
            "--file-shard-weights and --file-shard-targets-sha256 require --file-shard-targets"
        )
    plugin = FileShards(config.rootpath, count, index, pins, targets, weights)
    if expected is not None and plugin.digest != expected.strip().lower():
        raise pytest.UsageError(
            f"--file-shard-targets {targets_path} holds {len(plugin.balanced or {})} file(s) "
            f"with digest {plugin.digest}, not the expected {expected}: this shard was given "
            "a different list from the rest of the run"
        )
    config.pluginmanager.register(plugin, "ci-file-shards")


class FileShards:
    """Filter File collectors, never individual items.

    Using the collect-report hook rather than replacing config.args matters:
    explicit file arguments bypass pytest's collect_ignore rules. At this seam,
    normal discovery has already applied those rules, but Module.collect has
    not yet imported the file. This also works for explicit file arguments,
    non-Python File collectors, and each xdist worker's independent collection.
    Only ``--file-shard-targets`` reaches directory traversal, to skip whatever
    holds no target. The targets are owned by ``balance``; with no targets list
    every file keeps its pin or hash owner.
    """

    def __init__(
        self,
        root: Path,
        count: int,
        index: int,
        pins: Mapping[str, int] | None = None,
        targets: Iterable[Path] | None = None,
        weights: Mapping[str, int] | None = None,
    ) -> None:
        self.root = root
        self.count = count
        self.index = index
        self.pins = dict(pins or {})
        # Each target and every directory above it; discovery skips everything else.
        self.keep: set[Path] | None = None
        # Keyed by path, like ``keep``, so a target is found however the OS compares paths.
        self.balanced: dict[Path, int] | None = None
        self.digest: str | None = None
        if targets is not None:
            try:
                names = {t: t.relative_to(root).as_posix() for t in dict.fromkeys(targets)}
            except ValueError as exc:
                raise pytest.UsageError(
                    "file-sharded targets must be inside pytest's rootdir"
                ) from exc
            owners = balance(names.values(), weights or {}, count)
            self.keep = {p for t in names for p in (t, *t.parents)}
            self.balanced = {target: owners[name] for target, name in names.items()}
            self.digest = targets_digest(names.values())

    def pytest_ignore_collect(self, collection_path: Path) -> bool | None:
        # Never False: firstresult would let it override pytest's own ignores.
        if self.keep is None or collection_path in self.keep:
            return None
        return True

    @pytest.hookimpl(tryfirst=True)
    def pytest_make_collect_report(
        self, collector: pytest.Collector
    ) -> pytest.CollectReport | None:
        if not isinstance(collector, pytest.File):
            return None
        if self.owner(collector.path) == self.index:
            return None
        # Empty collection, not a skipped test: this file is run by its owner.
        # Keep pytest's ordinary exit 5 if the selected shard collects no tests;
        # an empty or broken selection must never silently fall back to all tests.
        return pytest.CollectReport(collector.nodeid, "passed", None, [])

    def owner(self, path: Path) -> int:
        """Return the one-based shard that runs ``path``: its placement, else pin or hash."""
        owner = None if self.balanced is None else self.balanced.get(path)
        if owner is not None:
            return owner
        try:
            return file_shard(path, self.root, self.count, self.pins)
        except ValueError as exc:
            raise pytest.UsageError("file-sharded targets must be inside pytest's rootdir") from exc

    def targets_line(self) -> str | None:
        """What a reader compares across the shards of one run; None without a targets list."""
        if self.balanced is None:
            return None
        owned = sum(owner == self.index for owner in self.balanced.values())
        return (
            f"file-shard targets: {len(self.balanced)} file(s), sha256 {self.digest}; "
            f"shard {self.index}/{self.count} owns {owned}"
        )

    def pytest_terminal_summary(
        self, terminalreporter: pytest.TerminalReporter, config: pytest.Config
    ) -> None:
        line = self.targets_line()
        # Once per run: an xdist worker has no terminal of its own to report on.
        if line is not None and not hasattr(config, "workerinput"):
            terminalreporter.write_line(line)

    def pytest_report_header(self) -> str:
        if self.balanced is not None:
            detail = f", {len(self.balanced)} targets placed by measured time"
        else:
            detail = f", {len(self.pins)} pinned" if self.pins else ""
        return (
            f"CI file shard {self.index}/{self.count}: whole files, assigned before import{detail}"
        )
