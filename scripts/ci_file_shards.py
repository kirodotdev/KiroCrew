"""Assign whole files to CI shards before pytest imports their test modules.

Leave discovery to pytest: testpaths, filename patterns, conftest ignores and
explicit targets retain their normal semantics. Only the owning shard collects
a file's items. Unlike pytest-split, other shards never import that file merely
to discard its tests. Directory/conftest imports and imports made by tests are
still shared costs; this is not a promise of a particular wall-clock speedup.

A file's owner is the SHA-256 of its root-relative POSIX path, unless
``--file-shard-pins`` names a pin file that lists it. A pin file gives the
heaviest files a fixed owner so the shards' total test time comes out even; it
is generated by ``scripts/ci_file_shard_pins.py`` from measured CI timings. A
file the pin file does not list (new, renamed) keeps its hash owner, so every
file still has exactly one owner, decided from its path alone.

``--file-shard-targets`` names a file listing the test files a subset run
wants, one root-relative path per line. Discovery still starts at testpaths but
skips every path that is not a target or a directory above one. The subset is
never put on argv: pytest walks a file argument's directory once per argument,
so a list of about 1,200 files takes up to an hour to collect. Spell it
``--file-shard-targets=PATH``: pytest picks its rootdir before this plugin's
options exist, so a separate PATH token outside the checkout counts as a test
argument there and can move the rootdir off the checkout.
"""

from __future__ import annotations

import hashlib
from collections.abc import Mapping
from pathlib import Path

import pytest


def hash_shard(relative: str, count: int) -> int:
    """Return the one-based hash owner of a root-relative POSIX path."""
    digest = hashlib.sha256(relative.encode("utf-8", errors="surrogatepass")).digest()
    return int.from_bytes(digest[:8], "big") % count + 1


def file_shard(path: Path, root: Path, count: int, pins: Mapping[str, int] | None = None) -> int:
    """Return a stable, one-based owner, independent of checkout path and OS."""
    relative = path.relative_to(root).as_posix()
    if pins and relative in pins:
        return pins[relative]
    return hash_shard(relative, count)


def read_pins(path: Path, count: int) -> dict[str, int]:
    """Parse a pin file: a ``# shards: N`` header, then ``<shard> <path>`` lines.

    Refuse anything ambiguous rather than guess an owner: a shard count other
    than the run's own (pins made for eight shards mean nothing for four), an
    owner outside 1..N, or a path listed twice.
    """
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise pytest.UsageError(f"cannot read --file-shard-pins {path}: {exc}") from exc
    declared = None
    pins: dict[str, int] = {}
    for number, line in enumerate(lines, 1):
        text = line.strip()
        if not text:
            continue
        if text.startswith("#"):
            key, _, value = text[1:].partition(":")
            if key.strip() == "shards":
                if not value.strip().isdigit():
                    raise pytest.UsageError(f"{path}:{number}: expected '# shards: <N>'")
                declared = int(value)
            continue
        owner, _, relative = text.partition(" ")
        if not owner.isdigit() or not relative or not 1 <= int(owner) <= count:
            raise pytest.UsageError(f"{path}:{number}: expected '<1..{count}> <path>'")
        if relative in pins:
            raise pytest.UsageError(f"{path}:{number}: {relative} is pinned twice")
        pins[relative] = int(owner)
    if declared != count:
        raise pytest.UsageError(
            f"{path} pins files for '# shards: {declared}', but --file-shards is {count}"
        )
    return pins


def read_targets(path: Path, root: Path) -> frozenset[Path]:
    """Parse a targets file: one root-relative test file per line, blanks skipped."""
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise pytest.UsageError(f"cannot read --file-shard-targets {path}: {exc}") from exc
    targets = frozenset(root / line.strip() for line in lines if line.strip())
    for target in targets:
        if not target.is_file():
            raise pytest.UsageError(f"--file-shard-targets {path} lists {target}, not a file")
    return targets


def pytest_addoption(parser: pytest.Parser) -> None:
    group = parser.getgroup("CI file sharding")
    group.addoption("--file-shards", type=int, default=None, help="Number of CI file shards")
    group.addoption("--file-shard", type=int, default=None, help="One-based CI file shard")
    group.addoption(
        "--file-shard-pins",
        default=None,
        help="Pin file giving listed files a fixed shard; other files keep their hash shard",
    )
    group.addoption(
        "--file-shard-targets",
        default=None,
        help="File listing the only test files to collect, one root-relative path per line",
    )


def pytest_configure(config: pytest.Config) -> None:
    count = config.getoption("file_shards")
    index = config.getoption("file_shard")
    pins_path = config.getoption("file_shard_pins")
    targets_path = config.getoption("file_shard_targets")
    if count is None and index is None:
        if pins_path is not None or targets_path is not None:
            raise pytest.UsageError(
                "--file-shard-pins and --file-shard-targets require --file-shards and --file-shard"
            )
        return
    if count is None or index is None or not 1 <= index <= count:
        raise pytest.UsageError("file sharding requires 1 <= --file-shard <= --file-shards")
    if config.getoption("splits", default=None):
        raise pytest.UsageError("file sharding cannot be combined with --splits")
    pins = read_pins(Path(pins_path), count) if pins_path is not None else {}
    targets = (
        read_targets(Path(targets_path), config.rootpath) if targets_path is not None else None
    )
    config.pluginmanager.register(
        FileShards(config.rootpath, count, index, pins, targets), "ci-file-shards"
    )


class FileShards:
    """Filter File collectors, never individual items.

    Using the collect-report hook rather than replacing config.args matters:
    explicit file arguments bypass pytest's collect_ignore rules. At this seam,
    normal discovery has already applied those rules, but Module.collect has
    not yet imported the file. This also works for explicit file arguments,
    non-Python File collectors, and each xdist worker's independent collection.
    Only ``--file-shard-targets`` reaches directory traversal, to skip whatever
    holds no target.
    """

    def __init__(
        self,
        root: Path,
        count: int,
        index: int,
        pins: Mapping[str, int] | None = None,
        targets: frozenset[Path] | None = None,
    ) -> None:
        self.root = root
        self.count = count
        self.index = index
        self.pins = dict(pins or {})
        # Each target and every directory above it; discovery skips everything else.
        self.keep = None if targets is None else {p for t in targets for p in (t, *t.parents)}

    def pytest_ignore_collect(self, collection_path: Path) -> bool | None:
        # Never False: firstresult would let it override pytest's own ignores.
        if self.keep is None or collection_path in self.keep:
            return None
        return True

    @pytest.hookimpl(tryfirst=True)
    def pytest_make_collect_report(
        self, collector: pytest.Collector
    ) -> pytest.CollectReport | None:
        if not isinstance(collector, pytest.File):
            return None
        try:
            owner = file_shard(collector.path, self.root, self.count, self.pins)
        except ValueError as exc:
            raise pytest.UsageError("file-sharded targets must be inside pytest's rootdir") from exc
        if owner == self.index:
            return None
        # Empty collection, not a skipped test: this file is run by its owner.
        # Keep pytest's ordinary exit 5 if the selected shard collects no tests;
        # an empty or broken selection must never silently fall back to all tests.
        return pytest.CollectReport(collector.nodeid, "passed", None, [])

    def pytest_report_header(self) -> str:
        pinned = f", {len(self.pins)} pinned" if self.pins else ""
        return (
            f"CI file shard {self.index}/{self.count}: whole files, assigned before import{pinned}"
        )
