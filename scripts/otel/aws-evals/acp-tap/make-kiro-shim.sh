#!/bin/sh
# Builds a wrapper for Crew's KIROCREW_KIRO_BIN override. Crew runs it as `<wrapper> acp --agent ...`;
# the wrapper starts acp-tap.js, which starts the real kiro-cli with the same arguments and records the ACP frames.
# Usage: ./make-kiro-shim.sh [path-to-real-kiro-cli]   (default: ~/.local/bin/kiro-cli)
set -e
cd "$(dirname "$0")"
HERE="$(pwd)"
REAL="${1:-$HOME/.local/bin/kiro-cli}"
NODE="$(command -v node || true)"
[ -x "$REAL" ] || { echo "real kiro-cli not found: $REAL" >&2; exit 1; }
[ -n "$NODE" ] || { echo "node not found on PATH" >&2; exit 1; }
REAL_DIR=$(CDPATH= cd -P "$(dirname "$REAL")" && pwd) || {
  echo "could not resolve real kiro-cli directory: $REAL" >&2
  exit 1
}
REAL="$REAL_DIR/$(basename "$REAL")"
mkdir -p shim
W="$HERE/shim/kiro-cli"
cat > "$W" <<EOF
#!/bin/sh
# generated by make-kiro-shim.sh
if [ "\${ACP_TAP_CONTENT-}" = "0" ]; then ACP_TAP_CONTENT=0; else ACP_TAP_CONTENT=1; fi
if [ "\${ACP_TAP_PROMPTS-}" = "0" ]; then ACP_TAP_PROMPTS=0; else ACP_TAP_PROMPTS=1; fi
export ACP_TAP_CONTENT ACP_TAP_PROMPTS
ACP_TAP_REAL_BIN="$REAL" exec "$NODE" "$HERE/acp-tap.js" "\$@"
EOF
chmod 755 "$W"
echo "wrapper: $W (real: $REAL, node: $NODE)"
