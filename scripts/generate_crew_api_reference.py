#!/usr/bin/env python3
"""Generate the Crew API reference pages from the Crew API spec.

Usage:
    python scripts/generate_crew_api_reference.py           # write the pages
    python scripts/generate_crew_api_reference.py --check   # exit 1 when they are stale

Reads ``docs/request-for-change/assets/crew-api/`` (``crew-public.yaml``,
``crew-owner.yaml`` and the ``components.yaml`` they share) and writes
``docs/reference/crew-api/``: an index, one page per group of endpoints and one page
of schemas. Every file in that directory is this script's output, so a page the spec
no longer produces is removed. ``test/test_crew_api_reference.py`` fails when the
committed pages differ from what the spec renders.

An endpoint is "Available now" when its operation carries ``x-crew-status: available``
and "Planned" otherwise. An available endpoint also says which callers the gateway
serves it to, from ``x-crew-available-to``: the owner only, or the owner and apps.
``test/test_crew_api_status_marks.py`` holds both marks against the gateway.
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Iterator, Mapping, Sequence
from pathlib import Path
from typing import Any

import yaml

_REPO_ROOT = Path(__file__).resolve().parent.parent
SPEC_DIR = _REPO_ROOT / "docs" / "request-for-change" / "assets" / "crew-api"
OUT_DIR = _REPO_ROOT / "docs" / "reference" / "crew-api"

#: The spec file of each API tier, in page order.
TIER_FILES = {"public": "crew-public.yaml", "owner": "crew-owner.yaml"}
COMPONENTS = "components.yaml"
SCHEMAS_PAGE = "schemas.md"

_METHODS = ("get", "post", "put", "patch", "delete")
_HEADER = "<!-- Generated by scripts/generate_crew_api_reference.py from the Crew API spec. -->\n"
_TIER_TITLES = {"public": "Public", "owner": "Owner"}
_TIER_BLURBS = {
    "public": "Endpoints an app calls with a credential the user granted it.",
    "owner": "Endpoints only the owner of this Kiro Crew may call. Every path starts "
    "with `/v1/crew/owner/`.",
}
#: The keys that make a schema an object or a choice between shapes.
_OBJECT_KEYS = frozenset({"properties", "oneOf", "anyOf", "allOf"})
#: The parts of ``x-crew-not-served-yet``, in page order.
_NOT_SERVED_PARTS = {
    "request-body": "Request body fields",
    "request-headers": "Request headers",
    "response-headers": "Response headers",
}
_PARAMETER_PLACES = {
    "path": "Path parameters",
    "query": "Query parameters",
    "header": "Request headers",
    "cookie": "Request cookies",
}

Docs = Mapping[str, Mapping[str, Any]]


def load_spec(spec_dir: Path = SPEC_DIR) -> dict[str, dict[str, Any]]:
    """The spec files, keyed by file name."""
    return {
        name: yaml.safe_load((spec_dir / name).read_text(encoding="utf-8"))
        for name in (*TIER_FILES.values(), COMPONENTS)
    }


class _Spec:
    """The loaded spec files, with ``$ref`` lookup across them."""

    def __init__(self, docs: Docs) -> None:
        self.docs = docs

    def deref(self, node: Any, doc: str) -> tuple[Any, str, str]:
        """Follow *node*'s ``$ref`` chain: the target, its file, and the last ref's name."""
        name = ""
        while isinstance(node, dict) and "$ref" in node:
            file_part, _, pointer = node["$ref"].partition("#")
            if file_part:
                doc = file_part.removeprefix("./")
            node = self.docs[doc]
            for part in pointer.strip("/").split("/"):
                node = node[part]
            name = pointer.rsplit("/", 1)[-1]
        return node, doc, name

    def schemas(self) -> dict[str, tuple[Mapping[str, Any], str]]:
        """Every named schema and the file it is in. A name is used once across the files."""
        found: dict[str, tuple[Mapping[str, Any], str]] = {}
        for doc, content in self.docs.items():
            for name, schema in content.get("components", {}).get("schemas", {}).items():
                if name in found:
                    raise ValueError(f"schema {name} is defined in {found[name][1]} and in {doc}")
                found[name] = (schema, doc)
        return found


def _prose(text: Any) -> str:
    """*text* on one line, with ``<`` escaped so a ``<placeholder>`` is not read as HTML."""
    return " ".join(str(text or "").split()).replace("<", "\\<")


def _cell(text: Any) -> str:
    """*text* as prose that is safe inside a table cell."""
    return _prose(text).replace("|", "\\|")


def _code(value: Any) -> str:
    """*value* as code: a string as it is, any other value the way JSON writes it."""
    return f"`{value if isinstance(value, str) else json.dumps(value)}`"


def _table(head: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    # A ``|`` a cell still carries, such as one inside a code value, would end the cell.
    lines += [
        "| " + " | ".join(re.sub(r"(?<!\\)\|", r"\\|", cell) for cell in row) + " |" for row in rows
    ]
    return [*lines, ""]


def _schema_link(name: str) -> str:
    return f"[{name}]({SCHEMAS_PAGE}#{name.lower()})"


def _type(spec: _Spec, schema: Any, doc: str) -> str:
    """A schema's type in words, naming a referenced schema by a link to its section."""
    if not isinstance(schema, dict):
        return "any"
    if "$ref" in schema:
        _, _, name = spec.deref(schema, doc)
        return _schema_link(name)
    for key in ("oneOf", "anyOf"):
        if key in schema:
            # Two shapes of one type read as that type once.
            return " or ".join(dict.fromkeys(_type(spec, option, doc) for option in schema[key]))
    if "allOf" in schema:
        parts = list(dict.fromkeys(_type(spec, part, doc) for part in schema["allOf"]))
        # A named schema with fields added to it reads as that schema.
        named = [part for part in parts if part != "object"]
        return " and ".join(named or parts)
    if "const" in schema:
        return _code(schema["const"])
    kind = schema.get("type", "object" if "properties" in schema else "any")
    if isinstance(kind, list):
        kind = " or ".join(kind)
    if schema.get("type") == "array":
        kind = "array of " + _type(spec, schema.get("items"), doc)
    if "enum" in schema:
        values = ", ".join(_code(value) for value in schema["enum"])
        kind = values if "type" not in schema else f"{kind}: {values}"
    if "format" in schema:
        kind += f" ({schema['format']})"
    limits = []
    if "minimum" in schema and "maximum" in schema:
        limits.append(f"{schema['minimum']} to {schema['maximum']}")
    elif "minimum" in schema:
        limits.append(f"at least {schema['minimum']}")
    elif "maximum" in schema:
        limits.append(f"at most {schema['maximum']}")
    if "default" in schema:
        limits.append("default " + _code(schema["default"]))
    if limits:
        kind += f" ({', '.join(limits)})"
    return kind


def _properties(spec: _Spec, schema: Any, doc: str) -> Iterator[tuple[str, Any, bool, str]]:
    """Each top-level field of an object schema: name, schema, required, file.

    The parts of an ``allOf`` are read as one object. A field's own fields are in the
    section of the schema its type names.
    """
    schema, doc, _ = spec.deref(schema, doc)
    if not isinstance(schema, dict):
        return
    for part in schema.get("allOf", ()):
        yield from _properties(spec, part, doc)
    required = set(schema.get("required", ()))
    for name, field in schema.get("properties", {}).items():
        yield name, field, name in required, doc


def _not_served(name: str, marked: Sequence[str]) -> str:
    """What opens the description of *name* when ``x-crew-not-served-yet`` names it.

    A marked name is a field, or a path under one (``tool_choice=none``): the whole
    field is not served, or only the paths listed.
    """
    under = [path for path in marked if re.split(r"[.\[=]", path, maxsplit=1)[0] == name]
    if name in under:
        return "**Not served yet.** "
    return "**Not served yet:** " + ", ".join(map(_code, under)) + ". " if under else ""


def _field_rows(
    spec: _Spec, schema: Any, doc: str, marked: Sequence[str] = ()
) -> list[tuple[str, ...]]:
    # A field that two parts of an ``allOf`` name is one field: the later part gives
    # its type, and it is required when either part requires it.
    merged: dict[str, tuple[Any, bool, str]] = {}
    for name, field, required, field_doc in _properties(spec, schema, doc):
        merged[name] = (field, required or (name in merged and merged[name][1]), field_doc)
    rows = []
    for name, (field, required, field_doc) in merged.items():
        target, _, _ = spec.deref(field, field_doc)
        description = field.get("description")
        # A field that only names a value type (an enum, a timestamp) takes that type's
        # description. An object's description is about the object and stays in its section.
        if not description and isinstance(target, dict) and not _OBJECT_KEYS & target.keys():
            description = target.get("description")
        rows.append(
            (
                _code(name),
                _type(spec, field, field_doc),
                "yes" if required else "no",
                _not_served(name, marked) + _cell(description),
            )
        )
    return rows


def _body(
    spec: _Spec, content: Mapping[str, Any], doc: str, what: str, marked: Sequence[str] = ()
) -> list[str]:
    """The fields of each media type of a request or response body."""
    lines: list[str] = []
    for media, body in content.items():
        schema = body.get("x-crew-sse-data", body.get("schema", {}))
        rows = _field_rows(spec, schema, doc, marked)
        shape = _type(spec, schema, doc)
        if "x-crew-sse-data" in body:
            lines += [f"{what} (`{media}`): each `data:` line is one {shape}.", ""]
            events = body.get("x-crew-sse-events")
            if events:
                lines += ["Event types: " + ", ".join(_code(event) for event in events) + ".", ""]
        elif rows:
            lines += [f"{what} fields (`{media}`), {shape}:", ""]
            lines += _table(("Field", "Type", "Required", "Description"), rows)
        else:
            lines += [f"{what} (`{media}`): {shape}.", ""]
    return lines


def _callers(operation: Mapping[str, Any]) -> list[str]:
    """Who may call an operation, one line per kind of caller."""
    owner, embed = False, False
    scope_sets: list[list[str]] = []
    for requirement in operation.get("security", ()):
        for scheme, scopes in requirement.items():
            if scheme == "firstPartySession":
                owner = True
            elif scheme.startswith("embedCredential"):
                embed = True
            else:
                scope_sets.append(list(scopes))
    lines = []
    if owner:
        lines.append("The owner, with the owner's own sign-in.")
    scopes = [scope for group in scope_sets for scope in group]
    if scope_sets and not scopes:
        lines.append("An app, with any credential the user granted it.")
    elif scopes:
        named = " or ".join(_code(scope) for scope in scopes)
        lines.append(f"An app, with a credential that holds the scope {named}.")
    entitlement = operation.get("x-crew-entitlement")
    if entitlement:
        names = [entitlement] if isinstance(entitlement, str) else entitlement
        lines.append("The app also needs the entitlement " + " and ".join(map(_code, names)) + ".")
    if embed:
        lines.append("An embedded chat frame, with its embed credential.")
    return lines


def _status(operation: Mapping[str, Any]) -> str:
    """ "Planned", or "Available now" with the callers the gateway serves the operation to."""
    if operation.get("x-crew-status") != "available":
        return "Planned"
    served = operation.get("x-crew-available-to", ())
    callers = {served} if isinstance(served, str) else set(served)
    if callers == {"owner"}:
        return "Available now: owner only"
    if callers == {"owner", "app"}:
        return "Available now: owner and apps"
    raise ValueError(f"x-crew-available-to is {served!r}: expected owner, or owner and app")


def _stability(operation: Mapping[str, Any]) -> str:
    return str(operation.get("x-crew-stability", "stable"))


def _operations(doc: Mapping[str, Any]) -> Iterator[tuple[str, str, Mapping[str, Any]]]:
    for path, item in doc["paths"].items():
        for method in _METHODS:
            if method in item:
                yield method.upper(), path, item[method]


def _anchor(method: str, path: str) -> str:
    """The anchor a Markdown renderer gives the heading ``METHOD path``."""
    kept = "".join(ch for ch in f"{method} {path}".lower() if ch.isalnum() or ch in " -_")
    return kept.replace(" ", "-")


def _errors(
    spec: _Spec, responses: Mapping[str, Any], doc: str, marked: Sequence[str] = ()
) -> list[str]:
    """The error table. *marked* holds the response headers the operation does not send."""
    rows = []
    for status, response in sorted(responses.items(), key=lambda item: str(item[0])):
        if not str(status).startswith(("4", "5")):
            continue
        response, _, _ = spec.deref(response, doc)
        examples = response.get("content", {}).get("application/json", {}).get("examples", {})
        # The code is the one the example's body carries. An example's name can say more
        # than its code, and one without a body is known by its name alone.
        found = [
            ((example or {}).get("value") or {}).get("error", {}).get("code", name)
            for name, example in examples.items()
        ]
        codes = ", ".join(_code(code) for code in dict.fromkeys(found))
        # A header this response declares and the operation's mark names is not sent
        # on the error either, whatever the shared description says.
        unsent = [name for name in response.get("headers", {}) if name in marked]
        note = (
            "**Not served yet:** "
            + ", ".join(map(_code, unsent))
            + ". Where this note says the response carries them, that is the planned behaviour. "
            if unsent
            else ""
        )
        rows.append((str(status), codes, note + _cell(response.get("description"))))
    if not rows:
        return []
    return [
        f"Errors. The response body is {_schema_link('Error')}; its `error.code` field "
        "holds the code.",
        "",
        *_table(("Status", "Codes", "Notes"), rows),
    ]


def _operation(spec: _Spec, tier: str, method: str, path: str, op: Mapping[str, Any]) -> list[str]:
    doc = TIER_FILES[tier]
    lines = [f"## {method} {path}", "", _cell(op.get("summary")).rstrip(".") + ".", ""]
    lines += _table(
        ("About", "This endpoint"),
        [
            ("Status", _status(op)),
            ("Tier", _TIER_TITLES[tier]),
            ("Stability", _stability(op)),
            ("Callers the API defines", " ".join(_callers(op))),
        ],
    )
    not_served = op.get("x-crew-not-served-yet", {})
    unknown = set(not_served) - set(_NOT_SERVED_PARTS)
    if unknown:
        raise ValueError(
            f"x-crew-not-served-yet on {method} {path} has the parts {sorted(unknown)}"
        )
    if not_served:
        lines += ["Not served yet:", ""]
        lines += [
            f"- {title}: " + ", ".join(map(_code, not_served[part])) + "."
            for part, title in _NOT_SERVED_PARTS.items()
            if not_served.get(part)
        ]
        lines += [""]
    if op.get("description"):
        lines += [_prose(op["description"]), ""]

    by_place: dict[str, list[tuple[str, ...]]] = {}
    for parameter in op.get("parameters", ()):
        parameter, parameter_doc, _ = spec.deref(parameter, doc)
        marked = not_served.get("request-headers", ()) if parameter["in"] == "header" else ()
        by_place.setdefault(parameter["in"], []).append(
            (
                _code(parameter["name"]),
                _type(spec, parameter.get("schema"), parameter_doc),
                "yes" if parameter.get("required") else "no",
                _not_served(parameter["name"], marked) + _cell(parameter.get("description")),
            )
        )
    for place, title in _PARAMETER_PLACES.items():
        if place in by_place:
            lines += [f"{title}:", ""]
            lines += _table(("Name", "Type", "Required", "Description"), by_place[place])
    request, request_doc, _ = spec.deref(op.get("requestBody", {}), doc)
    lines += _body(
        spec,
        request.get("content", {}),
        request_doc,
        "Request body",
        not_served.get("request-body", ()),
    )

    for status, response in op["responses"].items():
        if not str(status).startswith("2"):
            continue
        response, response_doc, _ = spec.deref(response, doc)
        lines += [f"Response `{status}`: {_cell(response.get('description')).rstrip('.')}.", ""]
        headers = []
        for name, header in response.get("headers", {}).items():
            header, header_doc, _ = spec.deref(header, response_doc)
            headers.append(
                (
                    _code(name),
                    _type(spec, header.get("schema"), header_doc),
                    _not_served(name, not_served.get("response-headers", ()))
                    + _cell(header.get("description")),
                )
            )
        if headers:
            lines += ["Response headers:", ""]
            lines += _table(("Name", "Type", "Description"), headers)
        lines += _body(spec, response.get("content", {}), response_doc, "Response body")
    return lines + _errors(spec, op["responses"], doc, not_served.get("response-headers", ()))


def _page_name(tier: str, tag: str) -> str:
    return f"{tier}-{tag}.md"


def _schemas_page(spec: _Spec) -> str:
    lines = [
        _HEADER,
        "# Crew API schemas",
        "",
        "The objects the [Crew API](README.md) endpoints send and receive, by name.",
        "",
        "This page does not say what the gateway serves. Whether an endpoint is available "
        "now, and which of its fields are not served yet, is on the endpoint's own page.",
        "",
    ]
    for name, (schema, doc) in sorted(spec.schemas().items()):
        lines += [f"## {name}", ""]
        if schema.get("description"):
            lines += [_prose(schema["description"]), ""]
        rows = _field_rows(spec, schema, doc)
        if rows:
            lines += _table(("Field", "Type", "Required", "Description"), rows)
        else:
            lines += [f"Type: {_type(spec, schema, doc)}.", ""]
    return "\n".join(lines).rstrip() + "\n"


def render(docs: Docs) -> dict[str, str]:
    """Every reference page, as file name to content, for the spec files in *docs*."""
    spec = _Spec(docs)
    pages: dict[str, list[str]] = {}
    index = [
        _HEADER,
        "# Crew API reference",
        "",
        "**Local pages, not a mirror.** This directory is Kiro Crew's own documentation "
        "and has no upstream source. It is a named exception in "
        "[the Reference index](../README.md).",
        "",
        "The Crew API is the HTTP API of a Kiro Crew gateway, under `/v1`. Each endpoint "
        "below is marked **Available now**, when the gateway serves it, or **Planned**. "
        "An available endpoint also says which callers the gateway serves it to: the "
        "owner only, or the owner and apps.",
        "",
        "- **Tier** says who an endpoint is for: Public endpoints are for apps, Owner "
        "endpoints for the owner of this Kiro Crew alone.",
        "- **Stability** says how far the request and response shapes are settled: "
        "`stable` shapes only gain fields, `preview` and `experimental` shapes may "
        "still change.",
        f"- Every refusal has one body, {_schema_link('Error')}. The objects the "
        f"endpoints send and receive are in [{SCHEMAS_PAGE}]({SCHEMAS_PAGE}).",
        "",
    ]
    for tier, file_name in TIER_FILES.items():
        doc = docs[file_name]
        index += [f"## {_TIER_TITLES[tier]} endpoints", "", _TIER_BLURBS[tier], ""]
        rows = []
        for method, path, op in _operations(doc):
            tag = op["tags"][0]
            name = _page_name(tier, tag)
            if name not in pages:
                pages[name] = [
                    _HEADER,
                    f"# Crew API: {tag} ({_TIER_TITLES[tier]} endpoints)",
                    "",
                    "Part of the [Crew API reference](README.md).",
                    "",
                ]
            pages[name] += _operation(spec, tier, method, path, op)
            rows.append(
                (
                    f"[`{method} {path}`]({name}#{_anchor(method, path)})",
                    _cell(op.get("summary")),
                    _status(op),
                    _stability(op),
                )
            )
        index += _table(("Endpoint", "What it does", "Status", "Stability"), rows)
    rendered = {name: "\n".join(lines).rstrip() + "\n" for name, lines in pages.items()}
    rendered["README.md"] = "\n".join(index).rstrip() + "\n"
    rendered[SCHEMAS_PAGE] = _schemas_page(spec)
    return rendered


def stale(out_dir: Path = OUT_DIR, spec_dir: Path = SPEC_DIR) -> list[str]:
    """The entries under *out_dir* that differ from what the spec renders, by name.

    An entry that is not a file, such as a directory, is never a page, so it is named too.
    """
    want = render(load_spec(spec_dir))
    have = (
        {
            path.name: path.read_text(encoding="utf-8") if path.is_file() else ""
            for path in out_dir.iterdir()
        }
        if out_dir.is_dir()
        else {}
    )
    return sorted(name for name in want.keys() | have.keys() if want.get(name) != have.get(name))


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        names = stale()
        for name in names:
            print(f"stale: docs/reference/crew-api/{name}")
        if names:
            print("run: python scripts/generate_crew_api_reference.py")
        return 1 if names else 0
    if argv:
        print(__doc__)
        return 2
    want = render(load_spec())
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    # Every entry here is this script's output. One that is not a file is not, and is
    # left for a person to remove.
    strays = sorted(path.name for path in OUT_DIR.iterdir() if not path.is_file())
    if strays:
        print(f"not a page, remove it from {OUT_DIR.name}/ first: {', '.join(strays)}")
        return 1
    for path in OUT_DIR.iterdir():
        if path.name not in want:
            path.unlink()
    for name, content in want.items():
        (OUT_DIR / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {len(want)} files to {OUT_DIR.relative_to(_REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
