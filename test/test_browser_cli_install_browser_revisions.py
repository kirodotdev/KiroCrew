"""Whether a cached browser build counts as downloaded.

The ``browsers.json`` manifest attributed to the serving CLI package, the required
revision match and its degradation, the Playwright cache-directory resolution, the
per-engine download status, and the port of Playwright's host-platform key. Detection
and install sequencing live in ``test_browser_cli_install.py``; the shared autouse pins
and fakes in ``browser_cli_install_helpers.py``.
"""

