"""The ``playwright-cli`` launcher in the managed tools leaf, and its attach time limit.

Agent shell commands spell ``playwright-cli``, and the agent ``PATH`` puts
``<data home>/playwright-cli/managed-bin`` first (:func:`kiro_crew.env._managed_browser_cli_dirs`).
That directory holds a generated POSIX launcher. For every argv that does not mention
``attach`` it is exactly ``exec <gateway-node> <playwright-cli.js> "$@"``: no extra
process, the same output and the same exit status as running the CLI directly.

An argv that mentions ``attach`` runs the CLI under :data:`ATTACH_GUARD_JS` instead,
which applies the limit only when the CLI's own parser reads the verb as ``attach``.
Without a token the
CLI waits, with no limit and no output, for the person to approve the debugger in
Chrome, and only cancelling Chrome's "is debugging this browser" bar ends that wait.
An agent turn waiting on that command sits on "thinking" until then. The guard runs
the same CLI with the same argv and inherited stdio, so an attach that finishes is
unchanged. At :data:`ATTACH_TIMEOUT_S` the CLI gets SIGTERM, which it forwards to the
daemon still waiting for approval, and the guard exits 124 with a message telling
the person to accept the prompt or retry.

Three writers produce these files and must agree byte for byte: ``playwright-cli.sh``
(the standalone installer), :func:`kiro_crew.browser_cli.install.install` (the
dashboard installer) and :func:`ensure_managed_launcher` at gateway startup, which
covers a host installed before the launcher existed. The shell installer embeds
:data:`POSIX_LAUNCHER_TEMPLATE` and :data:`ATTACH_GUARD_JS` as quoted heredocs and
fills the placeholders the way :func:`_render_posix_launcher` does;
``test_managed_launcher.py`` pins both copies and the rendered output together.

POSIX only. On Windows the leaf's ``.cmd`` launcher and npm's own shim are left as
they are, and so is a host whose only CLI is a system install.

Every write goes through a temporary file in the destination directory and an
``os.replace``, so a concurrent ``exec`` of the launcher sees the old file or the
new one. The leaf is sealed read-only inside agent sandboxes; only the gateway,
which runs outside them, writes here.
"""

from __future__ import annotations

import contextlib
import logging
import os
import stat
import tempfile
from pathlib import Path

from kiro_crew import platform_compat

logger = logging.getLogger("kiro_crew.browser_cli.install")

CLI_BIN = "playwright-cli"

#: The managed launcher's directory, relative to the managed tools leaf.
LAUNCHER_DIR = "managed-bin"
#: The attach guard's file name, in the managed tools leaf itself.
GUARD_NAME = "kirocrew-attach-guard.js"
#: The staged Node (POSIX) and the package entrypoint, relative to the leaf.
_NODE_NAME = "gateway-node"
_ENTRY_PARTS = ("lib", "node_modules", "@playwright", "cli", "playwright-cli.js")

#: How long an attach may wait for the person to approve it in Chrome. Generous on
#: purpose: the person has to notice Chrome, read the prompt and click it. The
#: guard script carries the same number in milliseconds; a test pins the two.
ATTACH_TIMEOUT_S = 120

_NODE_TOKEN = "@KIROCREW_NODE@"
_ENTRY_TOKEN = "@KIROCREW_ENTRY@"
_GUARD_TOKEN = "@KIROCREW_GUARD@"

#: The launcher, with shell-quoted paths substituted for the three tokens. An argv
#: that mentions ``attach`` anywhere runs under the guard, which reads it with the
#: CLI's own parser and applies the limit only when the verb is ``attach``. The CLI's
#: parser builds its verb from the words of argv, so it can name ``attach`` only when
#: some argument contains that word: no spelling and no CLI version can reach an
#: attach past the guard. Every other argv runs the CLI directly, with no extra
#: process.
POSIX_LAUNCHER_TEMPLATE = """\
#!/bin/sh
# Generated by Kiro Crew (playwright-cli.sh, the dashboard installer and the
# gateway write this same file). An argv that mentions `attach` runs under
# kirocrew-attach-guard.js, which applies the attach time limit only when the
# CLI's own parser reads the verb as `attach`; every other argv runs the CLI
# directly.
for _kc_arg in "$@"; do
  case "$_kc_arg" in
    *attach*) exec @KIROCREW_NODE@ @KIROCREW_GUARD@ @KIROCREW_ENTRY@ "$@" ;;
  esac
done
exec @KIROCREW_NODE@ @KIROCREW_ENTRY@ "$@"
"""

#: The attach guard, run by the staged Node as
#: ``gateway-node kirocrew-attach-guard.js <playwright-cli.js> <args...>``.
ATTACH_GUARD_JS = r"""'use strict';
// Generated by Kiro Crew. The managed playwright-cli launcher runs this for an
// argv that mentions `attach`:  gateway-node kirocrew-attach-guard.js <playwright-cli.js> <args...>
//
// Without a token, `attach --extension` waits with no limit and no output for the
// person to approve the debugger in Chrome. This runs the same CLI with the same
// argv and inherited stdio, so an attach that finishes keeps its output and exit
// status. One still running at TIMEOUT_MS gets SIGTERM, which the CLI forwards to
// its daemon so the waiting daemon stops with it, and this exits 124 saying what
// to do, whatever the stopped CLI exited with.
const { spawn } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const TIMEOUT_MS = 120000;
const KILL_GRACE_MS = 3000;
const TIMEOUT_EXIT = 124;
const FORWARDED = ['SIGINT', 'SIGTERM', 'SIGHUP'];
// The options program.js adds to help.json's list before it parses argv, read
// from that file because they differ between CLI versions; these are 0.1.22's,
// for a program.js whose list cannot be found.
const PROGRAM_BOOLEANS = ['all', 'g', 'help', 'json', 'raw', 'version'];

const programBooleans = (client) => {
  try {
    const source = fs.readFileSync(path.join(client, 'program.js'), 'utf-8');
    const list = /const booleanOptions = \[([^\]]*)\]/.exec(source);
    if (!list) return PROGRAM_BOOLEANS;
    return [...list[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  } catch (error) {
    return PROGRAM_BOOLEANS;
  }
};

const entry = process.argv[2];
const args = process.argv.slice(3);

// The verb as the CLI itself reads argv: its own minimist and option list, from
// the playwright-core that serves this entrypoint. The package's `exports` map
// hides these files, so only its exported package.json is resolved and they are
// loaded by absolute path beside it. null when that layout cannot be loaded.
const verbLikeTheCli = () => {
  try {
    const manifest = require.resolve('playwright-core/package.json', {
      paths: [path.dirname(entry)],
    });
    const client = path.join(path.dirname(manifest), 'lib', 'tools', 'cli-client');
    const { minimist } = require(path.join(client, 'minimist.js'));
    const help = require(path.join(client, 'help.json'));
    const boolean = [...help.booleanOptions, ...programBooleans(client)];
    return minimist(args, { boolean, string: ['_'] })._[0];
  } catch (error) {
    return null;
  }
};

const verb = verbLikeTheCli();
// The launcher sends every argv that mentions `attach`; the limit applies only
// when the CLI's own parse names `attach` as the verb. Without that parser, only
// an argv whose first word is `attach` counts: any earlier word could be an
// option's value, so a moved layout never puts a limit on another verb.
const guarded = verb !== null ? verb === 'attach' : args[0] === 'attach';

const message =
  `playwright-cli attach: Chrome did not approve the connection within ${TIMEOUT_MS / 1000}s, ` +
  'so the attach was stopped. Accept Chrome\'s debugging prompt ' +
  '(the Playwright extension\'s Connect prompt; keep the "is debugging this browser" bar ' +
  'open), or retry the attach.\n';

const child = spawn(process.execPath, [entry, ...args], { stdio: 'inherit' });
let timedOut = false;
let killTimer;

for (const signal of FORWARDED) {
  process.on(signal, () => {
    if (!timedOut) child.kill(signal);
  });
}

const timer = guarded
  ? setTimeout(() => {
      timedOut = true;
      child.kill('SIGTERM');
      killTimer = setTimeout(() => child.kill('SIGKILL'), KILL_GRACE_MS);
    }, TIMEOUT_MS)
  : undefined;

const exitLike = (code, signal) => {
  if (signal) {
    for (const forwarded of FORWARDED) process.removeAllListeners(forwarded);
    process.kill(process.pid, signal);
    setTimeout(() => process.exit(128 + (os.constants.signals[signal] || 0)), 1000);
    return;
  }
  process.exit(code === null ? 1 : code);
};

child.on('error', (error) => {
  clearTimeout(timer);
  process.stderr.write(`playwright-cli: ${error.message}\n`);
  process.exit(127);
});

child.on('exit', (code, signal) => {
  clearTimeout(timer);
  clearTimeout(killTimer);
  // The CLI was stopped by the deadline: whatever it exits with (its own SIGTERM
  // handler can leave it exiting 0), the attach did not complete.
  if (timedOut) {
    process.stderr.write(message);
    process.exit(TIMEOUT_EXIT);
  }
  exitLike(code, signal);
});
"""


def _shell_quote(value: str) -> str:
    """*value* as one single-quoted POSIX shell word.

    Byte-identical to ``_shell_quote`` in ``playwright-cli.sh``: every embedded
    single quote is closed, escaped and reopened, so ``$(...)``, backticks and
    spaces in a path stay data.
    """
    return "'" + value.replace("'", "'\\''") + "'"


def _render_posix_launcher(node: str, entry: str, guard: str) -> str:
    """The launcher for these absolute paths, as ``playwright-cli.sh`` writes it.

    The tokens are replaced in the same order the shell installer's ``awk`` pass
    replaces them, so a path that happens to contain a later token renders the
    same way in both writers.
    """
    text = POSIX_LAUNCHER_TEMPLATE
    text = text.replace(_NODE_TOKEN, _shell_quote(node))
    text = text.replace(_GUARD_TOKEN, _shell_quote(guard))
    return text.replace(_ENTRY_TOKEN, _shell_quote(entry))


def _is_regular_file(path: Path) -> bool:
    try:
        return stat.S_ISREG(os.lstat(path).st_mode)
    except OSError:
        return False


def _current(path: Path, content: bytes, executable: bool) -> bool:
    """Whether *path* is already a regular file holding *content*.

    Read without following a link: a symlink at the launcher's name is stale by
    definition, and ``os.replace`` swaps the link itself rather than writing
    through it.
    """
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except OSError:
        return False
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_size != len(content):
            return False
        if executable and not info.st_mode & stat.S_IXUSR:
            return False
        with os.fdopen(fd, "rb", closefd=False) as handle:
            return handle.read() == content
    finally:
        os.close(fd)


def _write_atomically(path: Path, content: bytes, mode: int) -> None:
    fd, incoming = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}-", suffix=".incoming")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
        os.chmod(incoming, mode)
        os.replace(incoming, path)
    finally:
        with contextlib.suppress(OSError):
            os.unlink(incoming)


def ensure_managed_launcher() -> bool:
    """Write the managed launcher and attach guard when either is missing or stale.

    Does nothing on Windows, when the leaf has no managed install (no staged
    ``gateway-node`` or no package entrypoint), or when the leaf or its launcher
    directory is a symlink. Compares content first and writes only on a mismatch,
    so a current host is never rewritten. Never raises: a failed write is logged
    and the host keeps whichever launcher it had, so a gateway start is never
    blocked by it. Returns whether a file was written.
    """
    if platform_compat.IS_WINDOWS:
        return False
    try:
        return _ensure_posix_launcher()
    except Exception as exc:  # noqa: BLE001 - must never block install or startup
        logger.warning("could not write the managed %s launcher: %s", CLI_BIN, exc)
        return False


def _ensure_posix_launcher() -> bool:
    # Through the facade, like every other caller, so a patch of the managed leaf
    # applied there reaches this read; imported here because the facade imports
    # this module.
    from kiro_crew.browser_cli import install

    root = install._managed_cli_root()
    if root.is_symlink() or not root.is_dir():
        return False
    resolved = root.resolve(strict=True)
    node = resolved / _NODE_NAME
    entry = resolved.joinpath(*_ENTRY_PARTS)
    if not (_is_regular_file(node) and _is_regular_file(entry)):
        return False
    guard = resolved / GUARD_NAME
    launcher_dir = resolved / LAUNCHER_DIR
    launcher = launcher_dir / CLI_BIN

    wrote = False
    # The guard first: a launcher that names it is only ever published once it
    # exists.
    guard_bytes = ATTACH_GUARD_JS.encode("utf-8")
    if not _current(guard, guard_bytes, executable=False):
        _write_atomically(guard, guard_bytes, 0o644)
        wrote = True
    if launcher_dir.is_symlink():
        raise OSError(f"{launcher_dir} is a symlink")
    launcher_dir.mkdir(mode=0o755, exist_ok=True)
    launcher_bytes = _render_posix_launcher(str(node), str(entry), str(guard)).encode("utf-8")
    if not _current(launcher, launcher_bytes, executable=True):
        _write_atomically(launcher, launcher_bytes, 0o755)
        wrote = True
    if wrote:
        logger.info("wrote the managed %s launcher at %s", CLI_BIN, launcher)
    return wrote
