"""Frozen inventory of every name ``kiro_crew.security`` exports.

The security controls are split across submodules of this package while
``kiro_crew.security`` stays the only import path. Callers reach names as
attributes of the package -- public API, and private helpers that tests read and
patch -- so "the split changed nothing" is a claim about this list: every name
here must resolve on the facade, and resolve to the SAME object the submodule
that owns it holds.

The list is frozen rather than derived, because deriving it from the facade
would make it agree with any facade. A name leaves this list only when the
symbol it names is deliberately deleted.

Lazily populated cache slots are NOT exported. A module attribute that starts as
``None`` and is rebound through ``global`` on first use is a write the facade's
attribute mirroring cannot see, so a re-export would hold the stale ``None`` while
the owner holds the live value -- two live versions of one control. Callers go
through the owner's accessor, which is the only path that was ever correct.
"""

