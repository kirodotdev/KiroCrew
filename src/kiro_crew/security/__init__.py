# Facade machinery
# ---------------------------------------------------------------------------
# The security controls are split by responsibility across submodules of this
# package, and ``kiro_crew.security`` stays the only import path: every name a
# submodule owns is re-exported here, private helpers included, because callers
# and tests reach them as attributes of the package and patch them by dotted
# string. Two properties have to hold for that to keep being true after a name
# moves out of this file.
#
# 1. A read here answers with the object the owning submodule holds. Resolving it
#    through the owner on each access is what makes that true by construction
#    rather than by a copy that agrees at import and can drift afterwards. The
#    frozen list in ``_exports`` is what keeps the set of names checkable.
# 2. Setting the attribute HERE reaches the owning submodule. A caller inside
#    that submodule resolves the name through its own globals, so a patch
#    applied only here would leave it running the unpatched object -- the test
#    passes while testing nothing. ``_ReExportModule`` below is what closes that,
#    so every existing patch site stays as written.
#
# Both halves resolve the owner through ``_submodule``, which reads ``sys.modules`` first and
# calls ``importlib.import_module`` only on a miss.  That leaves one place a value lives (the
# owner's namespace) and one place a module lives (``sys.modules``), so neither half has a
# second copy to keep in step.
#
# The table below is grouped by owning submodule, groups in alphabetical order, and a name belongs
# to the submodule that DEFINES it, or, for the mirror facades ``argv_floor``, ``denied_rules``,
# ``exfil``, ``paths`` and ``redaction``, to the facade that serves it from its owner. Names
# imported for this module's own use from outside the package -- the standard library and other
# ``kiro_crew`` modules -- are not in the table: no submodule owns them, so there is no owner to
# resolve them through, and they stay ordinary attributes of this module. Two outside names are
# the exception: ``SecurityEventLog`` and ``maintenance_executor`` belong to ``deny_gate``, whose
# audit emitters are the only readers of the binding this module held, so a patch written here
# reaches the module those readers run in (``exfil_oauth`` imports its own ``SecurityEventLog``).

