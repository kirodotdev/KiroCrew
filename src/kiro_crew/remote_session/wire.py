"""Authenticated, resumable, integrity-checked byte stream for remote sessions.

A provider tunnel (``coder ssh``) is not trusted to be byte exact (an SSM port
forward can turn a final LF into CR), so every byte crosses it exactly once, in
order, from the authenticated peer, across reconnects. Sans-IO and stdlib-only;
the guest copies this file beside its worker.

Wire format: ASCII lines ended by CR or LF (so a substituted CR cannot join two
lines), space-separated fields that never contain CR, LF or a space.

Handshake, once per connection, whichever side dialled::

    worker:  H <version> <session-id> <server-nonce>
    gateway: J <session-id> <client-nonce> <recv-next> <mac>
    worker:  W <recv-next> <mac>

``mac`` is HMAC-SHA256 under the session secret over the role label, session
id, both nonces and ``recv-next``: both sides prove the secret, and neither a
replay nor an altered resume position passes. Each connection derives its own
key; every later line carries a truncated HMAC under it and the sender's
direction label, so a frame cannot be forged, reflected or replayed::

    D <seq> <mac> <base64 piece>   stream data, pieces of at most PIECE_BYTES
    A <seq> <mac>                  cumulative ack: every seq <= this arrived
    N <seq> <mac>                  resend from this seq (bad line or gap)
    P <n> <mac> / Q <n> <mac>      keepalive ping / pong (the lease heartbeat)
    R <reason> <mac>               worker is retiring
    X <reason>.<final-seq> <mac>   no data after final-seq will ever be sent

Sequence numbers and unacked data persist across connections: on attach each
side resends from the peer's ``recv-next``; duplicates are dropped and a gap or
bad line is answered with N.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import os
import re
from collections import OrderedDict
from dataclasses import dataclass
from typing import Optional

VERSION = 1
PIECE_BYTES = 32 * 1024
#: A data line is at most ~44 KB (base64 of PIECE_BYTES plus header).
MAX_LINE_BYTES = 64 * 1024
MAX_HANDSHAKE_LINE_BYTES = 512
DEFAULT_MAX_UNACKED_BYTES = 8 * 1024 * 1024
SECRET_MIN_BYTES = 32
MAX_RTO_SECONDS = 30.0
#: Guest exits after this long without an authenticated gateway; above the
#: link's 300 s lease so a restart reconnects first.
ORPHAN_TIMEOUT_SECONDS = 600
#: An unattached spare is retired before its orphan clock can stop it.
SPARE_MAX_AGE_SECONDS = ORPHAN_TIMEOUT_SECONDS * 4 // 5

GATEWAY = "gateway"
WORKER = "worker"

_SESSION_ID_RE = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
_NONCE_RE = re.compile(rb"[0-9a-f]{32}\Z")
_SEQ_RE = re.compile(rb"(?:0|[1-9][0-9]{0,17})\Z")
_REASON_RE = re.compile(rb"[a-z0-9_-]{1,40}\Z")
_TERMINATOR = re.compile(rb"[\r\n]")
_MAC_CHARS = 32
_LABEL = {GATEWAY: b"g2w", WORKER: b"w2g"}


class WireError(Exception):
    """The peer violated the protocol in a way resending cannot repair."""


class AuthError(WireError):
    """The peer could not prove it holds the session secret."""


class BufferFull(WireError):
    """Unacknowledged data would exceed the configured bound; apply backpressure."""


def new_secret() -> bytes:
    """A fresh per-session secret. Generated by the gateway at allocation."""
    return os.urandom(SECRET_MIN_BYTES)


def validate_session_id(session_id: str) -> bytes:
    if not isinstance(session_id, str) or not _SESSION_ID_RE.match(session_id):
        raise ValueError("session id must be 1-64 characters of [A-Za-z0-9_-]")
    return session_id.encode("ascii")


def _validate_secret(secret: bytes) -> bytes:
    if not isinstance(secret, bytes) or len(secret) < SECRET_MIN_BYTES:
        raise ValueError(f"session secret must be at least {SECRET_MIN_BYTES} bytes")
    return secret


def _mac(key: bytes, *parts: bytes) -> bytes:
    digest = hmac.new(key, b"\x1f".join(parts), hashlib.sha256).hexdigest()
    return digest[:_MAC_CHARS].encode("ascii")


def _same(a: bytes, b: bytes) -> bool:
    return hmac.compare_digest(a, b)


def _seq(field: bytes) -> int:
    if not _SEQ_RE.match(field):
        raise ValueError("bad sequence number")
    return int(field)


def split_lines(buf: bytes, limit: int) -> tuple[list[bytes], bytes, bool]:
    """Return (lines, remainder, overflowed); an unterminated remainder over
    ``limit`` is discarded so a peer cannot grow memory without bound."""
    parts = _TERMINATOR.split(buf)
    rest = parts.pop()
    overflow = False
    if len(rest) > limit:
        rest, overflow = b"", True
    return [p for p in parts if p], rest, overflow


@dataclass(frozen=True)
class Attachment:
    """What a completed handshake hands to :meth:`Endpoint.attach`."""

    key: bytes
    peer_recv_next: int


def _connection_key(secret: bytes, sid: bytes, server_nonce: bytes, client_nonce: bytes) -> bytes:
    return hmac.new(
        secret, b"\x1f".join((b"key", sid, server_nonce, client_nonce)), hashlib.sha256
    ).digest()


class WorkerHandshake:
    """Worker side of one connection's handshake."""

    def __init__(self, session_id: str, secret: bytes) -> None:
        self._sid = validate_session_id(session_id)
        self._secret = _validate_secret(secret)
        self._server_nonce = os.urandom(16).hex().encode("ascii")

    def hello(self) -> bytes:
        return b"H %d %s %s\n" % (VERSION, self._sid, self._server_nonce)

    def on_join(self, line: bytes, recv_next: int) -> tuple[Attachment, bytes]:
        """Verify J; return the attachment and the W line to send."""
        fields = line.split(b" ")
        if len(fields) != 5 or fields[0] != b"J":
            raise AuthError("expected a join line")
        _, sid, client_nonce, peer_recv, mac = fields
        if not _same(sid, self._sid) or not _NONCE_RE.match(client_nonce):
            raise AuthError("join does not match this session")
        try:
            peer_recv_next = _seq(peer_recv)
        except ValueError as exc:
            raise AuthError("join carries a bad resume position") from exc
        expected = _mac(
            self._secret, b"join", self._sid, self._server_nonce, client_nonce, peer_recv
        )
        if not _same(mac, expected):
            raise AuthError("join authentication failed")
        recv = b"%d" % recv_next
        reply_mac = _mac(
            self._secret, b"welcome", self._sid, self._server_nonce, client_nonce, recv
        )
        key = _connection_key(self._secret, self._sid, self._server_nonce, client_nonce)
        return Attachment(key, peer_recv_next), b"W %s %s\n" % (recv, reply_mac)


class GatewayHandshake:
    """Gateway side of one connection's handshake."""

    def __init__(self, session_id: str, secret: bytes) -> None:
        self._sid = validate_session_id(session_id)
        self._secret = _validate_secret(secret)
        self._client_nonce = os.urandom(16).hex().encode("ascii")
        self._server_nonce: Optional[bytes] = None

    def on_hello(self, line: bytes, recv_next: int) -> bytes:
        """Verify H's shape; return the J line to send."""
        fields = line.split(b" ")
        if len(fields) != 4 or fields[0] != b"H":
            raise AuthError("expected a hello line")
        _, version, sid, server_nonce = fields
        if version != b"%d" % VERSION:
            raise WireError(f"unsupported protocol version {version!r}")
        if not _same(sid, self._sid) or not _NONCE_RE.match(server_nonce):
            raise AuthError("hello does not match this session")
        self._server_nonce = server_nonce
        recv = b"%d" % recv_next
        mac = _mac(self._secret, b"join", self._sid, server_nonce, self._client_nonce, recv)
        return b"J %s %s %s %s\n" % (self._sid, self._client_nonce, recv, mac)

    def on_welcome(self, line: bytes) -> Attachment:
        if self._server_nonce is None:
            raise AuthError("welcome before hello")
        fields = line.split(b" ")
        if len(fields) != 3 or fields[0] != b"W":
            raise AuthError("expected a welcome line")
        _, peer_recv, mac = fields
        try:
            peer_recv_next = _seq(peer_recv)
        except ValueError as exc:
            raise AuthError("welcome carries a bad resume position") from exc
        expected = _mac(
            self._secret, b"welcome", self._sid, self._server_nonce, self._client_nonce, peer_recv
        )
        if not _same(mac, expected):
            raise AuthError("welcome authentication failed")
        key = _connection_key(self._secret, self._sid, self._server_nonce, self._client_nonce)
        return Attachment(key, peer_recv_next)


class Endpoint:
    """One side's stream state. Persists across connections; one attached at a time."""

    def __init__(
        self,
        role: str,
        *,
        max_unacked_bytes: int = DEFAULT_MAX_UNACKED_BYTES,
        retransmit_after: float = 1.0,
        ack_every: int = 16,
    ) -> None:
        if role not in _LABEL:
            raise ValueError("role must be gateway or worker")
        self.role = role
        self._send_label = _LABEL[role]
        self._recv_label = _LABEL[WORKER if role == GATEWAY else GATEWAY]
        self.max_unacked_bytes = max_unacked_bytes
        self.retransmit_after = retransmit_after
        self.ack_every = ack_every
        self.next_seq = 0
        self.recv_next = 0
        self._unacked: "OrderedDict[int, bytes]" = OrderedDict()
        self.unacked_bytes = 0
        #: Set once a peer sends X: the stream ends when recv_next reaches it.
        self.peer_final: Optional[int] = None
        self.peer_close_reason = ""
        self.stats = dict.fromkeys(
            ("sent", "resent", "delivered", "bad", "gap", "dup", "nack_sent", "attached"), 0
        )
        self._key: Optional[bytes] = None
        self._retire_arg: Optional[bytes] = None
        self._close_arg: Optional[bytes] = None
        self._sticky_at = 0.0
        self._buf = b""
        self._unacked_in = 0
        self._last_nack: Optional[tuple[int, float]] = None
        self._last_progress = 0.0
        self._rto = retransmit_after
        self.last_inbound = 0.0

    @property
    def attached(self) -> bool:
        return self._key is not None

    def attach(self, attachment: Attachment, now: float, leftover: bytes = b"") -> bytes:
        """Bind to a newly authenticated connection; return resend bytes.

        A resume position outside what this side holds cannot be repaired."""
        oldest = next(iter(self._unacked), self.next_seq)
        if not oldest <= attachment.peer_recv_next <= self.next_seq:
            raise WireError("peer resume position is outside this stream")
        self._key = attachment.key
        self._buf = leftover
        self._unacked_in = 0
        self._last_nack = None
        self._rto = self.retransmit_after
        self._last_progress = now
        self.last_inbound = now
        self.stats["attached"] += 1
        self._ack_through(attachment.peer_recv_next - 1, now)
        resend = b"".join(self._data_frame(seq, piece) for seq, piece in self._unacked.items())
        return resend + self._sticky()

    def detach(self) -> None:
        self._key = None
        self._buf = b""

    def _data_frame(self, seq: int, piece: bytes) -> bytes:
        assert self._key is not None
        s = b"%d" % seq
        return b"D %s %s %s\n" % (s, _mac(self._key, self._send_label, b"D", s, piece), piece)

    def _control(self, kind: bytes, arg: bytes) -> bytes:
        if self._key is None:
            return b""
        return b"%s %s %s\n" % (kind, arg, _mac(self._key, self._send_label, kind, arg))

    def can_accept(self, size: int) -> bool:
        return self.unacked_bytes + size * 4 // 3 + 4 <= self.max_unacked_bytes

    def write(self, data: bytes, now: float) -> bytes:
        """Queue stream bytes; return wire bytes when attached (else b"")."""
        if not data:
            return b""
        if self._close_arg is not None:
            raise WireError("write after close")
        pieces = [
            base64.b64encode(data[i : i + PIECE_BYTES]) for i in range(0, len(data), PIECE_BYTES)
        ]
        size = sum(len(p) for p in pieces)
        if self.unacked_bytes + size > self.max_unacked_bytes:
            raise BufferFull("unacknowledged data would exceed the bound")
        if not self._unacked:
            self._last_progress = now
        out = []
        for piece in pieces:
            seq = self.next_seq
            self.next_seq += 1
            self._unacked[seq] = piece
            self.unacked_bytes += len(piece)
            if self._key is not None:
                out.append(self._data_frame(seq, piece))
        self.stats["sent"] += len(pieces)
        return b"".join(out)

    def ping(self, n: int) -> bytes:
        return self._control(b"P", b"%d" % n)

    def retire(self, reason: str) -> bytes:
        """Announce retirement. Remembered and repeated on every later attach."""
        self._retire_arg = self._reason(reason)
        return self._control(b"R", self._retire_arg)

    def close(self, reason: str) -> bytes:
        """Promise no data after the current position; repeated on every
        later attach and retransmission tick."""
        self._close_arg = b"%s.%d" % (self._reason(reason), self.next_seq)
        return self._control(b"X", self._close_arg)

    def _sticky(self) -> bytes:
        out = b""
        if self._retire_arg is not None:
            out += self._control(b"R", self._retire_arg)
        if self._close_arg is not None:
            out += self._control(b"X", self._close_arg)
        return out

    @staticmethod
    def _reason(reason: str) -> bytes:
        raw = reason.encode("ascii", "replace")
        if not _REASON_RE.match(raw):
            raise ValueError("reason must be 1-40 characters of [a-z0-9_-]")
        return raw

    def _ack_through(self, seq: int, now: float) -> None:
        advanced = False
        while self._unacked:
            first = next(iter(self._unacked))
            if first > seq:
                break
            self.unacked_bytes -= len(self._unacked.pop(first))
            advanced = True
        if advanced:
            self._last_progress = now
            self._rto = self.retransmit_after

    def _resend_from(self, seq: int, now: float) -> bytes:
        out = [self._data_frame(s, p) for s, p in self._unacked.items() if s >= seq]
        self.stats["resent"] += len(out)
        self._last_progress = now
        return b"".join(out)

    def _nack(self, now: float) -> bytes:
        last = self._last_nack
        if last and last[0] == self.recv_next and now - last[1] < self.retransmit_after:
            return b""
        self._last_nack = (self.recv_next, now)
        self.stats["nack_sent"] += 1
        return self._control(b"N", b"%d" % self.recv_next)

    def _ack(self) -> bytes:
        self._unacked_in = 0
        return self._control(b"A", b"%d" % (self.recv_next - 1)) if self.recv_next else b""

    def feed(self, data: bytes, now: float) -> tuple[bytes, bytes, list[tuple[str, str]]]:
        """Wire bytes in: (stream bytes delivered, wire bytes out, events), events
        being ("pong", n), ("retire", reason) and ("close", reason)."""
        if self._key is None:
            return b"", b"", []
        lines, self._buf, overflow = split_lines(self._buf + data, MAX_LINE_BYTES)
        delivered: list[bytes] = []
        out: list[bytes] = []
        events: list[tuple[str, str]] = []
        if overflow:
            self.stats["bad"] += 1
            out.append(self._nack(now))
        for line in lines:
            out.append(self._line(line, now, delivered, events))
        if self._unacked_in >= self.ack_every:
            out.append(self._ack())
        return b"".join(delivered), b"".join(out), events

    def _line(self, line: bytes, now: float, delivered: list[bytes], events: list) -> bytes:
        assert self._key is not None
        fields = line.split(b" ")
        kind = fields[0]
        if kind == b"D" and len(fields) == 4:
            seq_f, mac, piece = fields[1], fields[2], fields[3]
            if not _same(mac, _mac(self._key, self._recv_label, b"D", seq_f, piece)):
                self.stats["bad"] += 1
                return self._nack(now)
            try:
                seq = _seq(seq_f)
                payload = base64.b64decode(piece, validate=True)
            except (ValueError, binascii.Error):
                self.stats["bad"] += 1
                return self._nack(now)
            self.last_inbound = now
            if seq < self.recv_next:
                self.stats["dup"] += 1
                return self._ack()
            if seq > self.recv_next:
                self.stats["gap"] += 1
                return self._nack(now)
            delivered.append(payload)
            self.recv_next += 1
            self._unacked_in += 1
            self.stats["delivered"] += 1
            return b""
        if len(fields) != 3 or kind not in (b"A", b"N", b"P", b"Q", b"R", b"X"):
            self.stats["bad"] += 1
            return self._nack(now)
        arg, mac = fields[1], fields[2]
        if not _same(mac, _mac(self._key, self._recv_label, kind, arg)):
            self.stats["bad"] += 1
            return self._nack(now)
        self.last_inbound = now
        try:
            if kind == b"A":
                self._ack_through(_seq(arg), now)
            elif kind == b"N":
                seq = _seq(arg)
                self._ack_through(seq - 1, now)
                return self._resend_from(seq, now)
            elif kind == b"P":
                _seq(arg)
                return self._control(b"Q", arg)
            elif kind == b"Q":
                events.append(("pong", arg.decode("ascii")))
            elif kind == b"R":
                if not _REASON_RE.match(arg):
                    raise ValueError("bad reason")
                events.append(("retire", arg.decode("ascii")))
            else:  # X
                reason, _, final = arg.rpartition(b".")
                if not _REASON_RE.match(reason):
                    raise ValueError("bad reason")
                self.peer_final = _seq(final)
                self.peer_close_reason = reason.decode("ascii")
                events.append(("close", self.peer_close_reason))
        except ValueError:
            self.stats["bad"] += 1
        return b""

    def tick(self, now: float) -> bytes:
        """Flush a pending ack; on stalled acks resend only the oldest frame, with
        backoff (the whole window would flood a slow tunnel; N recovers the rest)."""
        if self._key is None:
            return b""
        out = []
        if self._unacked_in:
            out.append(self._ack())
        if self._unacked and now - self._last_progress >= self._rto:
            seq, piece = next(iter(self._unacked.items()))
            out.append(self._data_frame(seq, piece))
            self.stats["resent"] += 1
            self._last_progress = now
            self._rto = min(self._rto * 2, MAX_RTO_SECONDS)
        if (self._retire_arg or self._close_arg) and now - self._sticky_at >= self.retransmit_after:
            out.append(self._sticky())
            self._sticky_at = now
        return b"".join(out)

    @property
    def peer_finished(self) -> bool:
        """The peer closed and every byte it promised has been delivered."""
        return self.peer_final is not None and self.recv_next >= self.peer_final
