"""The delegated-token scope: one explicit ``allow`` / ``deny`` tag per dashboard route.

A token minted through the ``dashboard_proxy`` grant carries ``via_app=<app>`` (see
``dashboard/delegated_scope.py``). It READS what an owner reads from a browser (chat,
sessions, running agents) and nothing that mints, moves or widens a credential, returns a
stored credential, or changes the control plane: grant approvals, app install / enable /
disable / register, the owner-enable marker, sandbox, approval-mode and sign-in settings,
restart and upgrade, ``/v1/crew/owner/*``. It reads no host file and no whole export either:
every route that serves file content, lists a directory outside the app, or exports the
install or the memory is ``deny`` here, and a new one must be listed in
``delegated_scope.CONTENT_READ_REVIEWED`` with a reason or it fails the route walk.

This table holds reads only (the ``GET`` entry; ``HEAD`` follows it). A write (any other
method) is open to a delegated token only where ``delegated_scope.ALLOW_WRITES`` lists it,
so no write is tagged here.

Keys are the route's canonical path (aiohttp ``resource.canonical``). A read route that is
not listed is DENIED at runtime (``delegated_scope.route_tag`` answers ``None``), and
``test_delegated_route_tags.py`` walks the whole route table and fails on a read route
missing here, so a new read route has to be tagged on purpose. Reads of admin pages are
allowed; a read that returns a stored credential is ``deny``.
"""

