"""Crew's isolation probe: two bench stores must never see each other's items.

Two units are written with disjoint, generated facts. Each is then asked for the
other's facts by their exact wording. Any returned item that belongs to the other
unit, by origin id or by the other unit's marker in its text, is a leak; the
expected count is 0. Generated here, so no data is fetched.
"""

from __future__ import annotations

from ..item_corpus import BenchItem, ItemCorpus, ItemQuery, ItemUnit
from . import SuiteInfo

_SUBJECTS = ("the lighthouse", "the orchard", "the observatory", "the ferry", "the bakery")
_FACTS = ("opens at {h} o'clock", "was painted {c}", "is run by {n}")
_COLORS = ("teal", "amber", "crimson", "ivory", "slate")
_NAMES = ("Ilse", "Marek", "Tova", "Quinn", "Anouk")


def _facts(side: int) -> list[str]:
    out = []
    for n, subject in enumerate(_SUBJECTS):
        k = (n + side * 2) % 5
        fact = _FACTS[(n + side) % 3].format(h=k + 5 + side * 3, c=_COLORS[k], n=_NAMES[k])
        out.append(f"In unit {'AB'[side]}, {subject} {fact}.")
    return out


def corpus() -> ItemCorpus:
    texts = [_facts(0), _facts(1)]
    units = []
    for side in (0, 1):
        items = tuple(
            BenchItem(f"{'ab'[side]}{n}", t, "fact", None, "iso") for n, t in enumerate(texts[side])
        )
        other = 1 - side
        queries = tuple(
            ItemQuery(
                query_id=f"iso-{'ab'[side]}-{n}",
                text=texts[other][n],
                category="isolation",
                unanswerable=True,
                extra=(("leak_prefix", "ab"[other]), ("leak_marker", f"In unit {'AB'[other]},")),
            )
            for n in range(len(texts[other]))
        )
        units.append(ItemUnit(f"iso-{'ab'[side]}", items, queries))
    return ItemCorpus("isolation", "pair", tuple(units))


def load(
    variant: str = "pair", *, limit: int | None = None, allow_download: bool = True
) -> ItemCorpus:
    return corpus()


SUITE = SuiteInfo(
    id="isolation",
    name="Crew isolation probe",
    variants=("pair",),
    license="MIT (generated by Crew)",
    license_note="",
    dims=("M10",),
    ingest_modes=("items",),
    scorer="isolation",
    loader=load,
)
