"""An externally anchored KB golden set, sampled from BEIR's NFCorpus.

The authored sets (``kb_golden_v1``/``v2``) were written, labelled and audited by
us, so a blind spot shared by author and annotators reads as a correct label. This
set takes its relevance judgments from a published benchmark instead: NFCorpus
(Boteva et al., 2016) as BEIR distributes it, whose judgments come from the links
in NutritionFacts.org articles to the medical papers they cite. Nothing about our
retriever or our annotators shaped them. ``bench kb-retrieval --external`` scores
it after the authored set, never instead of it: NFCorpus has no correction,
contradiction, retraction or abstention queries, and those are why the authored
set exists. Every query is scored as ``clean_fact``, because NFCorpus models none
of the other classes. Relevance is binary here, as in every KB golden set: both of
NFCorpus's grades (2, a direct citation; 1, an indirect one) count as gold, so the
nDCG printed is not the benchmark's graded nDCG.

Nothing is vendored. BEIR publishes NFCorpus under CC BY-SA 4.0 (its dataset
card); the repo commits only ids, in ``data/kb_external_nfcorpus_v1.json``, and the
text is fetched on demand at pinned revisions with pinned SHA-256s through
``datasets.ensure``, the LoCoMo/LongMemEval precedent. The specs live here rather
than in ``datasets.SPECS`` because ``bench retrieval`` hands any key there to a
memory-corpus adapter, and these files are not a memory corpus.

The manifest is generated by :func:`sample_manifest` and committed, so a later
change to the sampler cannot silently change the set. Sampling keeps only
multi-gold test queries (2-5 relevant papers), since a single-gold query cannot
exercise ``recall_all`` or MAP, and pads each with papers the benchmark judged
relevant to a neighbouring query (one that shares a gold paper with it). Those
rivals are picked from the benchmark's own judgments, not by any retriever's
similarity, and are scored the way the benchmark judged them: a paper nobody
judged for the query counts as not relevant to it. To regenerate, first change
``NAME`` (so two prints of different samples never share a name), then::

    python -m kiro_crew.eval.bench.kb_external > src/kiro_crew/eval/bench/data/<NAME>.json
"""

from __future__ import annotations

import csv
import gzip
import json
import random
from collections import defaultdict
from pathlib import Path

from kiro_crew.eval.bench import datasets
from kiro_crew.eval.bench.kb_retrieval import KBDoc, KBGoldenSet, KBQuery, golden_set_dir
from kiro_crew.eval.bench.safepath import read_bytes_nofollow, read_text_nofollow

NAME = "kb_external_nfcorpus_v1"
SEED = 0
N_QUERIES = 40
MIN_GOLD, MAX_GOLD = 2, 5
RIVALS_PER_QUERY = 3

_CORPUS_REVISION = "e28763e68d85db0fa71652ba3c4afabf8c5b3bb7"
_QRELS_REVISION = "a451b3b26d3ae1358f259c1a3a4dd61fcea35a65"
_HF = "https://huggingface.co/datasets/BeIR"

SPECS: tuple[datasets.DatasetSpec, ...] = (
    datasets.DatasetSpec(
        key="nfcorpus_corpus",
        dataset="beir-nfcorpus",
        variant="corpus",
        url=f"{_HF}/nfcorpus/resolve/{_CORPUS_REVISION}/corpus.jsonl.gz",
        filename="beir-nfcorpus-corpus.jsonl.gz",
        approx_bytes=1_978_293,
        sha256="ae4d6ab2ab88d880e7e180776c956a09c19c43a703457742cd850d2422035802",
        measures_retrieval=True,
    ),
    datasets.DatasetSpec(
        key="nfcorpus_queries",
        dataset="beir-nfcorpus",
        variant="queries",
        url=f"{_HF}/nfcorpus/resolve/{_CORPUS_REVISION}/queries.jsonl.gz",
        filename="beir-nfcorpus-queries.jsonl.gz",
        approx_bytes=79_080,
        sha256="baba3504a2736b0e32265962f04acc4fecfaf9649e0ea08e49ff441246f75364",
        measures_retrieval=True,
    ),
    datasets.DatasetSpec(
        key="nfcorpus_qrels_test",
        dataset="beir-nfcorpus",
        variant="qrels-test",
        url=f"{_HF}/nfcorpus-qrels/resolve/{_QRELS_REVISION}/test.tsv",
        filename="beir-nfcorpus-qrels-test.tsv",
        approx_bytes=279_572,
        sha256="f8fba6ef3d4dd9c3a242a8ba4ae38276fc3622fce7dcbae764766d564542fd2a",
        measures_retrieval=True,
    ),
)

Corpus = dict[str, dict]
Qrels = dict[str, set[str]]


def manifest_path() -> Path:
    return golden_set_dir() / f"{NAME}.json"


def _jsonl_gz(path: Path, what: str) -> list[dict]:
    text = gzip.decompress(read_bytes_nofollow(path, what=what)).decode("utf-8")
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def read_beir(
    corpus_path: Path, queries_path: Path, qrels_path: Path
) -> tuple[Corpus, dict[str, str], Qrels]:
    """Parse one BEIR task: ``id -> doc``, ``id -> query text``, ``qid -> relevant ids``.

    A qrels score of 0 means judged NOT relevant, so only positive scores count.
    """
    corpus = {d["_id"]: d for d in _jsonl_gz(corpus_path, "BEIR corpus")}
    queries = {q["_id"]: q["text"] for q in _jsonl_gz(queries_path, "BEIR queries")}
    qrels: Qrels = defaultdict(set)
    rows = csv.reader(
        read_text_nofollow(qrels_path, what="BEIR qrels").splitlines()[1:], delimiter="\t"
    )
    for qid, doc_id, score in rows:
        if int(score) > 0:
            qrels[qid].add(doc_id)
    return corpus, queries, dict(qrels)


def sample_manifest(queries: dict[str, str], qrels: Qrels, *, seed: int = SEED) -> dict:
    """Pick the query and doc ids; the same inputs and seed give the same manifest."""
    rng = random.Random(seed)
    candidates = sorted(
        q for q, gold in qrels.items() if q in queries and MIN_GOLD <= len(gold) <= MAX_GOLD
    )
    picked = sorted(rng.sample(candidates, min(N_QUERIES, len(candidates))))
    judged_for: dict[str, set[str]] = defaultdict(set)
    for qid, gold in qrels.items():
        for doc_id in gold:
            judged_for[doc_id].add(qid)
    doc_ids: set[str] = set()
    for qid in picked:
        gold = qrels[qid]
        neighbours = {other for doc_id in gold for other in judged_for[doc_id]} - {qid}
        rivals = sorted({d for other in neighbours for d in qrels[other]} - gold)
        doc_ids |= gold | set(rng.sample(rivals, min(RIVALS_PER_QUERY, len(rivals))))
    return {
        "name": NAME,
        "benchmark": "BEIR nfcorpus, test split",
        "revisions": {"corpus": _CORPUS_REVISION, "qrels": _QRELS_REVISION},
        "seed": seed,
        "query_ids": picked,
        "doc_ids": sorted(doc_ids),
    }


def build_golden(
    manifest: dict, corpus: Corpus, queries: dict[str, str], qrels: Qrels
) -> KBGoldenSet:
    """Materialize the manifest's ids into a validated golden set; gold comes from the qrels."""
    golden = KBGoldenSet(
        name=manifest["name"],
        docs=tuple(
            KBDoc(id=d, title=corpus[d]["title"], content=corpus[d]["text"])
            for d in manifest["doc_ids"]
        ),
        queries=tuple(
            KBQuery(
                id=q,
                query_class="clean_fact",
                question=queries[q],
                gold_doc_ids=tuple(sorted(qrels[q])),
            )
            for q in manifest["query_ids"]
        ),
    )
    golden.validate()
    return golden


def _fetched_beir() -> tuple[Corpus, dict[str, str], Qrels]:
    corpus_path, queries_path, qrels_path = (datasets.ensure(spec) for spec in SPECS)
    return read_beir(corpus_path, queries_path, qrels_path)


def load_external_golden() -> KBGoldenSet:
    """The committed manifest built against the fetched (and checksum-verified) files."""
    manifest = json.loads(read_text_nofollow(manifest_path(), what="external golden manifest"))
    return build_golden(manifest, *_fetched_beir())


if __name__ == "__main__":
    _, _queries, _qrels = _fetched_beir()
    print(json.dumps(sample_manifest(_queries, _qrels), indent=2))
